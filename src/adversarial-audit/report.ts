export function renderAdversarialImportReport(attacks: readonly LoadedAdversarialAttack[]): string {
  const imported = attacks.filter((a) => isImportedAdversarialRecord(a.record));
  const counted = imported.filter((a) => a.record.counts);
  const nonOpenAi = imported.filter((a) => a.record.attacker.provider !== "codex");
  return [
    "# Adversarial import evidence",
    "",
    "External adversarial audits count only after import preserves provider identity, transcript,",
    "package hash, verifier hash/output and replay/triage state. Prepared Anthropic/Gemini bundles are",
    "not evidence until a completed run is imported and validated.",
    "",
    "| item | value |",
    "|---|---:|",
    `| imported records | ${imported.length} |`,
    `| counted imported records | ${counted.length} |`,
    `| imported non-OpenAI records | ${nonOpenAi.length} |`,
    "",
    "| attack | family | provider | model | status | counts | replay | triage | challenge hash |",
    "|---|---|---|---|---|---|---|---|---|",
    ...imported.map((a) => {
      const r = a.record;
      return `| \`${r.attackId}\` | \`${r.familyId}\` | ${r.attacker.provider} | ${r.attacker.model} | ${r.status} | ${r.counts ? "yes" : "no"} | ${r.exploitReplay.status} | ${r.triage.decision} | ${r.challengeHash === null ? "none" : `\`${r.challengeHash}\``} |`;
    }),
    "",
    counted.length === 0
      ? "No imported adversarial audit currently counts as verifier-integrity evidence."
      : "Counted imported rows above have passed the same hash/replay/countability rules as local audits.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}

