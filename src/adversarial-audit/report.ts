const icon = (v: "pass" | "fail" | "n/a"): string =>
  v === "pass" ? "pass" : v === "fail" ? "**FAIL**" : "n/a";
const yesNo = (v: boolean): string => (v ? "yes" : "no");

export function renderAdversarialReadinessReport(audits: readonly AdversarialReadinessAudit[]): string {
  const ready = audits.filter((a) => a.verdict === "adversarial-ready").map((a) => a.familyId);
  const pending = audits.filter((a) => a.verdict !== "adversarial-ready").map((a) => a.familyId);
  return [
    "# Adversarial verifier-integrity readiness",
    "",
    "Adversarial readiness asks whether the verifier can be attacked under a declared threat model.",
    "It is separate from package leak checks, mutant detection, model difficulty and human solvability.",
    "",
    "Cheat resistance is not the same claim as no bypass found. Cheat resistance is the design requirement; adversarial audit is the attempted exploit record.",
    "",
    "| family | readiness | package hash | campaign | bundle | blockers |",
    "|---|---|---|---|---|---|",
    ...audits.map((a) => {
      const blockers = a.checks.filter((c) => c.verdict === "fail").map((c) => `\`${c.id}\``);
      return `| \`${a.familyId}\` | **${a.verdict}** | ${a.packageHash === null ? "none" : `\`${a.packageHash}\``} | ${a.campaignId === null ? "none" : `\`${a.campaignId}\``} | ${a.bundlePath === null ? "none" : `\`${a.bundlePath}\``} | ${blockers.length === 0 ? "none" : blockers.join(", ")} |`;
    }),
    "",
    "## Current Reading",
    "",
    `Adversarial-ready families: ${ready.length === 0 ? "none" : ready.map((f) => `\`${f}\``).join(", ")}.`,
    `Audit-pending families: ${pending.length === 0 ? "none" : pending.map((f) => `\`${f}\``).join(", ")}.`,
    "",
    "A ready verdict means the attack campaign is prepared and hash-pinned. It does not mean anyone",
    "has tried to exploit the verifier, and it does not mean no bypass exists.",
    "",
    "## Audit Checks",
    "",
    ...audits.flatMap((a) => [
      `### \`${a.familyId}\``,
      "",
      "| check | result | detail |",
      "|---|---|---|",
      ...a.checks.map((c) => `| \`${c.id}\` | ${icon(c.verdict)} | ${c.detail.replace(/\|/g, "\\|")} |`),
      "",
    ]),
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}

export function renderAdversarialAuditReport(summaries: readonly AdversarialEvidenceSummary[]): string {
  const audited = summaries.filter((s) => s.countedNoBypassAudits > 0).map((s) => s.familyId);
  const bypassed = summaries.filter((s) => s.unrepairedBypasses > 0).map((s) => s.familyId);
  const uncounted = summaries.reduce((n, s) => n + s.uncountedRecords, 0);
  const invalid = summaries.reduce((n, s) => n + s.invalidCountedRecords, 0);
  return [
    "# Adversarial verifier-integrity audit",
    "",
    "This report counts attempted verifier bypass audits only when the attacker saw the current public",
    "package, the transcript and verifier output are preserved, and the run was not a refusal,",
    "infrastructure error, timeout, stale hash or contaminated attack.",
    "",
    "| family | claim level | package hash | ready | counted no-bypass | counted bypass | unrepaired bypass | records | validation failures |",
    "|---|---|---|---|---:|---:|---:|---:|---|",
    ...summaries.map((s) => {
      const failures = s.validationFailures
        .map((f) => `${f.attackId}: ${f.codes.map((c) => `\`${c}\``).join(", ")}`)
        .join("; ");
      return `| \`${s.familyId}\` | **${s.claimLevel}** | ${s.packageHash === null ? "none" : `\`${s.packageHash}\``} | ${yesNo(s.adversarialReady)} | ${s.countedNoBypassAudits} | ${s.countedBypassAudits} | ${s.unrepairedBypasses} | ${s.auditRecords} | ${failures.length === 0 ? "none" : failures} |`;
    }),
    "",
    "## Current Reading",
    "",
    `Adversarial-audited families: ${audited.length === 0 ? "none" : audited.map((f) => `\`${f}\``).join(", ")}.`,
    `Families with unrepaired counted bypasses: ${bypassed.length === 0 ? "none" : bypassed.map((f) => `\`${f}\``).join(", ")}.`,
    `${uncounted} uncounted adversarial record(s) are preserved. ${invalid} counted record(s) are invalid.`,
    "",
    "No-bypass evidence is an attempted-exploit result, not a proof of security. A single no-bypass",
    "audit says one attacker under one declared threat model did not find a bypass.",
    "",
    "## Status Counts",
    "",
    "| family | not-run | no-bypass-found | bypass-found | exploit-attempt-blocked | provider-refusal | infrastructure-error | timeout | invalid-attack | stale-hash | contaminated | superseded |",
    "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ...summaries.map(
      (s) =>
        `| \`${s.familyId}\` | ${s.statusCounts["not-run"]} | ${s.statusCounts["no-bypass-found"]} | ${s.statusCounts["bypass-found"]} | ${s.statusCounts["exploit-attempt-blocked"]} | ${s.statusCounts["provider-refusal"]} | ${s.statusCounts["infrastructure-error"]} | ${s.statusCounts.timeout} | ${s.statusCounts["invalid-attack"]} | ${s.statusCounts["stale-hash"]} | ${s.statusCounts.contaminated} | ${s.statusCounts.superseded} |`,
    ),
    "",
    "## Bypass Classes",
    "",
    "| family | no-bypass | hidden-artifact-leak | ground-truth-rebinding | ledger-forgery | verifier-import-hijack | process-boundary-escape | challenge-hash-confusion | baseline-imposter | status-only-fake | artifact-substitution | environment-assumption | scorer-output-forgery |",
    "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ...summaries.map(
      (s) =>
        `| \`${s.familyId}\` | ${s.bypassCounts["no-bypass"]} | ${s.bypassCounts["hidden-artifact-leak"]} | ${s.bypassCounts["ground-truth-rebinding"]} | ${s.bypassCounts["ledger-forgery"]} | ${s.bypassCounts["verifier-import-hijack"]} | ${s.bypassCounts["process-boundary-escape"]} | ${s.bypassCounts["challenge-hash-confusion"]} | ${s.bypassCounts["baseline-imposter"]} | ${s.bypassCounts["status-only-fake"]} | ${s.bypassCounts["artifact-substitution"]} | ${s.bypassCounts["environment-assumption"]} | ${s.bypassCounts["scorer-output-forgery"]} |`,
    ),
    "",
    "## Countability Rules",
    "",
    "- `ADV_COUNTED_HASH_MISSING`: counted audit lacks the challenge hash.",
    "- `ADV_COUNTED_HASH_STALE`: counted audit targets a non-current challenge hash.",
    "- `ADV_COUNTED_NO_TRANSCRIPT`: counted audit has no preserved attacker transcript.",
    "- `ADV_COUNTED_NO_ATTACK_SURFACE`: counted audit declares no attack surface.",
    "- `ADV_COUNTED_NO_ACCESS_BOUNDARY`: counted audit lacks allowed/forbidden access boundaries.",
    "- `ADV_COUNTED_PROVIDER_REFUSAL`: provider refusal was counted.",
    "- `ADV_COUNTED_INFRA_ERROR`: infrastructure failure was counted.",
    "- `ADV_COUNTED_TIMEOUT`: timeout was counted.",
    "- `ADV_COUNTED_NO_COUNTABILITY_REASON`: counted audit has no reason explaining why it counts.",
    "- `ADV_COUNTED_NO_BYPASS_WITHOUT_VERIFIER`: no-bypass claim lacks preserved verifier output.",
    "- `ADV_COUNTED_BYPASS_WITHOUT_EXPLOIT`: bypass claim lacks exploit artifact.",
    "- `ADV_BYPASS_FIXED_WITHOUT_REPAIR`: bypass marked fixed with no repair record.",
    "- `ADV_REPAIR_CHANGED_PACKAGE_WITHOUT_INVALIDATION`: repair changed the package but did not invalidate old audits.",
    "- `ADV_CLAIM_WITHOUT_NO_BYPASS_AUDIT`: adversarial-audited claim has zero counted no-bypass audits.",
    "- `ADV_HIDDEN_ARTIFACT_IN_ATTACKER_CONTEXT`: hidden verifier/reference/scenario files entered attacker context.",
    "- `ADV_V2_COUNTED_NO_EXECUTION_PROFILE`: counted v2 audit lacks execution profile metadata.",
    "- `ADV_V2_COUNTED_NO_ISOLATION_PROFILE`: counted v2 audit lacks isolation profile metadata.",
    "- `ADV_V2_COUNTED_WEAK_ISOLATION`: counted v2 audit used an isolation profile that is not adequate.",
    "- `ADV_V2_COUNTED_NO_REPLAY_RESULT`: counted v2 audit lacks exploit replay output.",
    "- `ADV_V2_COUNTED_NO_TRIAGE`: counted v2 audit lacks mechanical bypass triage.",
    "- `ADV_V2_COUNTED_BYPASS_REPLAY_NOT_PASSING`: bypass did not replay as a verifier pass.",
    "- `ADV_V2_COUNTED_BYPASS_NO_CONTRACT_VIOLATION`: bypass did not violate the public contract.",
    "- `ADV_V2_COUNTED_BYPASS_FORBIDDEN_ACCESS`: bypass depended on forbidden access.",
    "- `ADV_V2_COUNTED_NO_BYPASS_NOT_ATTEMPTED`: no-bypass claim came from something other than a bypass attempt.",
    "- `ADV_V2_COUNTED_NO_BYPASS_THEORETICAL_ONLY`: no-bypass claim was only theoretical notes.",
    "- `ADV_V2_COUNTED_NORMAL_SOLUTION`: normal task solution was miscounted as verifier-integrity evidence.",
    "- `ADV_V2_COUNTED_PROBES_FAILING`: deterministic hardening probes failed.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}

export function renderAdversarialV2Report(summaries: readonly AdversarialEvidenceSummary[]): string {
  return [
    "# Adversarial Audit v2",
    "",
    "v2 adds mechanical exploit replay, explicit isolation profiles, bypass triage and deterministic",
    "hardening probes. It does not convert provider refusals or probe-only checks into no-bypass",
    "model evidence.",
    "",
    "| family | v2 records | counted v2 no-bypass | counted v2 bypass | container audits | imports | isolation records | replay ready | probes | claim level |",
    "|---|---:|---:|---:|---:|---:|---|---|---|---|",
    ...summaries.map((s) => {
      const isolation = Object.entries(s.isolationCounts)
        .filter(([, n]) => n > 0)
        .map(([id, n]) => `${id}:${n}`)
        .join(", ");
      const probes =
        s.packageHash === null
          ? "n/a"
          : s.hardeningProbesPass
            ? "pass"
            : `fail (${s.hardeningProbeFailures})`;
      return `| \`${s.familyId}\` | ${s.v2AuditRecords} | ${s.countedNoBypassV2Audits} | ${s.countedBypassV2Audits} | ${s.countedContainerNoBypassAudits + s.countedContainerBypassAudits} | ${s.importedAdversarialAudits} | ${isolation || "none"} | ${yesNo(s.exploitReplayReady)} | ${probes} | ${s.claimLevel} |`;
    }),
    "",
    "## Evidence Boundary",
    "",
    "- Counted no-bypass audits require a non-refusal attacker run, transcript, current challenge hash, verifier output, adequate isolation and no replayed bypass artifact.",
    "- Counted bypass audits require a preserved exploit artifact that replays against the current verifier and passes while violating the public contract.",
    "- Deterministic probes are regression hardening evidence only. They are not model adversarial audits.",
    "- One OpenAI/Codex audit remains one provider family. Repeated OpenAI runs are repeated trials, not cross-lab evidence.",
    "- Container/no-network audits are counted separately from fs-sandbox audits. A prepared container bundle is not a counted audit.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}

