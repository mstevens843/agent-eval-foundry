import type { HumanEvidenceSummary, HumanReadinessAudit } from "./types.js";

const icon = (v: "pass" | "fail" | "n/a"): string =>
  v === "pass" ? "pass" : v === "fail" ? "**FAIL**" : "n/a";
const yesNo = (v: boolean): string => (v ? "yes" : "no");
const esc = (s: string): string => s.replace(/\|/g, "\\|");

export function renderHumanReadinessReport(audits: readonly HumanReadinessAudit[]): string {
  const ready = audits.filter((a) => a.verdict === "human-ready").map((a) => a.familyId);
  const blocked = audits.filter((a) => a.verdict !== "human-ready").map((a) => a.familyId);
  return [
    "# Human readiness",
    "",
    "Human-readiness asks whether the public package can be handed to an independent engineer without",
    "hidden source, author memory or private hints. It is separate from reference solvability and from",
    "model difficulty.",
    "",
    "| family | human-readiness | package hash | visible files | blockers |",
    "|---|---|---|---:|---|",
    ...audits.map((a) => {
      const blockers = a.checks.filter((c) => c.verdict === "fail").map((c) => c.id);
      return `| \`${a.familyId}\` | **${a.verdict}** | ${a.packageHash === null ? "none" : `\`${a.packageHash}\``} | ${a.visibleFiles.length} | ${blockers.length === 0 ? "none" : blockers.map((b) => `\`${b}\``).join(", ")} |`;
    }),
    "",
    "## Current Reading",
    "",
    `Human-ready families: ${ready.length === 0 ? "none" : ready.map((f) => `\`${f}\``).join(", ")}.`,
    `Blocked or unavailable packages: ${blocked.length === 0 ? "none" : blocked.map((f) => `\`${f}\``).join(", ")}.`,
    "",
    "A ready verdict says the public package is complete enough for a clean-room human attempt. It does",
    "not say that a human has solved it.",
    "",
    "## Audit Checks",
    "",
    ...audits.flatMap((a) => [
      `### \`${a.familyId}\``,
      "",
      "| check | result | detail |",
      "|---|---|---|",
      ...a.checks.map((c) => `| \`${c.id}\` | ${icon(c.verdict)} | ${esc(c.detail)} |`),
      "",
    ]),
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}

export function renderHumanSolvabilityReport(summaries: readonly HumanEvidenceSummary[]): string {
  const evidenced = summaries.filter((s) => s.cleanHumanSolves > 0).map((s) => s.familyId);
  const pending = summaries
    .filter((s) => s.humanPackageReady && s.cleanHumanSolves === 0)
    .map((s) => s.familyId);
  const blocked = summaries.filter((s) => !s.humanPackageReady).map((s) => s.familyId);
  const contaminated = summaries.reduce((n, s) => n + s.nonCountingRecords, 0);
  const invalid = summaries.reduce((n, s) => n + s.invalidCountedRecords, 0);
  return [
    "# Human solvability",
    "",
    "Human-solvability evidence counts only independent clean-room solves against the current challenge",
    "hash, with transcript or notes, time record, and verifier output preserved. Assisted and",
    "contaminated walkthroughs are retained but do not count.",
    "",
    "| family | claim level | package hash | human-ready | clean solves | records | open ambiguity | validation failures |",
    "|---|---|---|---|---:|---:|---:|---|",
    ...summaries.map((s) => {
      const failures = s.validationFailures.flatMap((f) => f.codes).join(", ");
      return `| \`${s.familyId}\` | **${s.claimLevel}** | ${s.packageHash === null ? "none" : `\`${s.packageHash}\``} | ${yesNo(s.humanPackageReady)} | ${s.cleanHumanSolves} | ${s.reviewRecords} | ${s.unresolvedAmbiguities} | ${failures.length === 0 ? "none" : failures} |`;
    }),
    "",
    "## Current Reading",
    "",
    `Human-evidenced families: ${evidenced.length === 0 ? "none" : evidenced.map((f) => `\`${f}\``).join(", ")}.`,
    `Ready for clean-room review, pending an independent solve: ${pending.length === 0 ? "none" : pending.map((f) => `\`${f}\``).join(", ")}.`,
    `Not human-ready in this repo: ${blocked.length === 0 ? "none" : blocked.map((f) => `\`${f}\``).join(", ")}.`,
    `${contaminated} assisted or contaminated review record(s) are preserved and do not count. ${invalid} counted record(s) are invalid.`,
    "",
    "The clean claim levels are: `reference-solvable`, `human-ready`, `human-evidenced`. A family can",
    "ship on model/verifier gates while still being `human-ready` rather than `human-evidenced`.",
    "",
    "## Status Counts",
    "",
    "| family | not-run | clean-pass | clean-fail | ambiguous-spec | needed-private-context | timeout | assisted | contaminated | invalid-hash |",
    "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ...summaries.map(
      (s) =>
        `| \`${s.familyId}\` | ${s.statusCounts["not-run"]} | ${s.statusCounts["clean-pass"]} | ${s.statusCounts["clean-fail"]} | ${s.statusCounts["ambiguous-spec"]} | ${s.statusCounts["needed-private-context"]} | ${s.statusCounts.timeout} | ${s.statusCounts.assisted} | ${s.statusCounts.contaminated} | ${s.statusCounts["invalid-hash"]} |`,
    ),
    "",
    "## Countability Rules",
    "",
    "- `HUMAN_COUNTED_HASH_MISSING`: counted record lacks the reviewed or graded challenge hash.",
    "- `HUMAN_COUNTED_HASH_STALE`: counted record targets a non-current challenge hash.",
    "- `HUMAN_COUNTED_AUTHOR`: counted record was solved by an author or collaborator, not an independent engineer.",
    "- `HUMAN_COUNTED_SAW_HIDDEN`: counted record saw hidden verifier, reference, scenarios or source internals.",
    "- `HUMAN_COUNTED_PRIVATE_HINT`: counted record used private hints or private-context answers.",
    "- `HUMAN_COUNTED_NO_NOTES`: counted record has no preserved transcript or notes.",
    "- `HUMAN_COUNTED_NO_TIME_RECORD`: counted record has no start/end/elapsed/budget record.",
    "- `HUMAN_COUNTED_VERIFIER_NOT_RUN`: counted record has no preserved passing verifier output.",
    "- `HUMAN_COUNTED_PACKAGE_DIFFERS`: public package reviewed and package graded are not byte-identical.",
    "- `HUMAN_CLAIM_WITHOUT_CLEAN_RECORD`: a human-solvable claim has no clean independent solve behind it.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}
