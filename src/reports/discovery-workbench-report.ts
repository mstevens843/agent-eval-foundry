import type {
  DiscoveryCandidate,
  DiscoveryCandidateScore,
  DiscoveryNextStep,
  DiscoveryTaskShapeDraft,
  DiscoveryWorkbench,
  DiscoveryWorkbenchSummary,
  MergedCandidateEvidence,
  SurfaceCoverageGroup,
} from "../foundry/discovery-workbench.js";
import {
  DISCOVERY_NEXT_STEPS,
  SURFACE_COVERAGE_GROUPS,
  isLineageEvidenceStatus,
  mergeCandidateEvidence,
} from "../foundry/discovery-workbench.js";
import type { Registry } from "../foundry/registry.js";
import type { EvidenceLedger } from "../trials/evidence-lifecycle.js";
import { labelStaleRunsInProse } from "../trials/migration.js";

export interface DiscoveryWorkbenchReportInput {
  readonly registry: Registry;
  readonly workbench: DiscoveryWorkbench;
  readonly summary: DiscoveryWorkbenchSummary;
  /**
   * The evidence ledgers, for the queue reasons that narrate a decision by naming its run.
   *
   * Optional so the `discovery report` subcommand can render the workbench without loading every
   * family's trials; the `all` command, whose output is checked, always supplies them.
   */
  readonly ledgers?: readonly EvidenceLedger[];
}

const esc = (s: string): string => s.replace(/\|/g, "\\|");
const money = (n: number): string => `$${n.toFixed(0)}`;
const candidateById = (candidates: readonly DiscoveryCandidate[]): Map<string, DiscoveryCandidate> =>
  new Map(candidates.map((c) => [c.id, c]));

function sortedRows(counts: Readonly<Record<string, number>>): readonly string[] {
  return Object.entries(counts)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `| ${esc(k)} | ${v} |`);
}

function scoreRows(
  scores: readonly DiscoveryCandidateScore[],
  candidates: readonly DiscoveryCandidate[],
): readonly string[] {
  const byId = candidateById(candidates);
  return scores.map((s) => {
    const candidate = byId.get(s.candidateId);
    return `| \`${s.candidateId}\` | ${esc(candidate?.domain ?? "unknown")} | ${s.totalScore.toFixed(1)} | ${s.confidence.toFixed(2)} | ${s.recommendedAction} | ${s.cheapestNextEvidence} | ${esc(s.blockingReasons.map((b) => b.code).join(", ") || "none")} |`;
  });
}

function scoreBrief(score: DiscoveryCandidateScore, candidates: readonly DiscoveryCandidate[]): string {
  const candidate = candidateById(candidates).get(score.candidateId);
  return `\`${score.candidateId}\` (${candidate?.domain ?? "unknown"}, score ${score.totalScore.toFixed(1)}, ${score.cheapestNextEvidence})`;
}

/**
 * Renders a merged evidence record as one cell: the strongest provenance status the candidate
 * earned, plus the lineage adjustment that ranking applied on top of it. Both halves are shown so
 * the table cannot claim a promoted candidate is merely "lineage-penalized".
 */
function evidenceCell(evidence: MergedCandidateEvidence | undefined): string {
  if (evidence === undefined) return "score-only";
  if (isLineageEvidenceStatus(evidence.status) || evidence.lineageAdjustment === 0) return evidence.status;
  const sign = evidence.lineageAdjustment > 0 ? "+" : "";
  return `${evidence.status} (lineage ${sign}${evidence.lineageAdjustment.toFixed(1)})`;
}

export function renderDiscoveryCandidates(candidates: readonly DiscoveryCandidate[]): string {
  return [
    "# Discovery candidates",
    "",
    "These are planning inputs, not difficulty evidence. They exist so the foundry can kill, probe,",
    "transfer or promote benchmark ideas before paying for a full family build.",
    "",
    "| candidate | domain | mechanisms | proposed next step |",
    "|---|---|---|---|",
    ...candidates.map(
      (c) =>
        `| \`${c.id}\` | ${esc(c.domain)} | ${c.failureMechanisms.map((m) => `\`${m}\``).join(", ")} | ${c.proposedNextStep} |`,
    ),
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}

export function renderDiscoveryScores(
  scores: readonly DiscoveryCandidateScore[],
  candidates: readonly DiscoveryCandidate[],
): string {
  return [
    "# Discovery candidate scores",
    "",
    "Scores route cheap evidence. They are not model-difficulty evidence and must not be quoted as",
    "agent performance.",
    "",
    "| candidate | domain | score | confidence | recommended action | cheapest evidence | blockers |",
    "|---|---|---:|---:|---|---|---|",
    ...scoreRows(scores, candidates),
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}

export function renderDiscoveryNext(
  summary: DiscoveryWorkbenchSummary,
  candidates: readonly DiscoveryCandidate[],
): string {
  const evidence = mergeCandidateEvidence(summary.evidenceStatuses);
  return [
    "discovery workbench next actions",
    "candidate | action | evidence | probe status | score | reason",
    ...summary.topBuildOrProbeCandidates.map((s) => {
      const candidate = candidateById(candidates).get(s.candidateId);
      const status = evidence.get(s.candidateId);
      return `${s.candidateId} | ${s.recommendedAction} | ${s.cheapestNextEvidence} | ${evidenceCell(status)} | ${s.totalScore.toFixed(1)} | ${status?.reason ?? candidate?.taskFamilyHypothesis ?? "unknown"}`;
    }),
    "",
    "Candidate score is not difficulty evidence. Probe-ready is not trialed. Surface coverage is not axis diversity.",
    "",
  ].join("\n");
}

export function renderDiscoveryScaffoldSummary(draft: DiscoveryTaskShapeDraft): string {
  return [
    `family     ${draft.familyId}`,
    `candidate  ${draft.sourceCandidateId}`,
    `rules      ${draft.visibleRulesDraft.length}`,
    `knobs      ${draft.knobs.length}`,
    `mutants    ${draft.expectedMutants.length}`,
    `transfers  ${draft.transferLinks.length}`,
    "",
  ].join("\n");
}

export function renderDiscoveryWorkbenchReport(input: DiscoveryWorkbenchReportInput): string {
  const { registry, summary, workbench } = input;
  // Queue reasons are recorded prose, carried here rather than composed here, and several of them
  // narrate a decision by naming the run it was made on. The reason text is not rewritten — it is a
  // record of what was decided and when — but a run id inside it is annotated where the run has since
  // been withdrawn, so no reader meets it as live evidence.
  const reason = (text: string): string => labelStaleRunsInProse(esc(text), input.ledgers ?? []);
  const evidence = mergeCandidateEvidence(summary.evidenceStatuses);
  const lineageEvidence = summary.evidenceStatuses.filter((item) => isLineageEvidenceStatus(item.status));
  const warnings = summary.warnings.length === 0 ? ["none"] : summary.warnings;
  const killed =
    summary.killedCheaply.length === 0
      ? ["_none_"]
      : summary.killedCheaply.map((s) => {
          const blockers = s.blockingReasons.map((b) => b.reason).join("; ") || "proposed cheap kill";
          return `- ${scoreBrief(s, workbench.candidates)}: ${blockers}`;
        });
  const repair =
    summary.needingRepair.length === 0
      ? ["_none_"]
      : summary.needingRepair.map((s) => {
          const blockers =
            s.blockingReasons.map((b) => b.reason).join("; ") || "held for more paper evidence";
          return `- ${scoreBrief(s, workbench.candidates)}: ${blockers}`;
        });
  const transfers =
    summary.transferOpportunities.length === 0
      ? ["_none_"]
      : summary.transferOpportunities.slice(0, 12).map((s) => {
          const candidate = candidateById(workbench.candidates).get(s.candidateId);
          return `- \`${s.candidateId}\` -> ${candidate?.transferPotential.targetDomains.join(", ") ?? "unknown"}${candidate?.transferPotential.linkedTransferTests.length ? ` (${candidate.transferPotential.linkedTransferTests.map((t) => `\`${t}\``).join(", ")})` : ""}`;
        });

  return [
    "# Discovery Workbench v1",
    "",
    "Discovery Workbench v1 is the machine that feeds the adaptive funnel. It keeps candidate ideas",
    "cheap and comparable before they become task shapes, packages, trials or ship claims.",
    "",
    "```text",
    "Candidate -> mechanism probe -> transfer test -> task shape -> family -> trials -> axis analysis -> ship/kill/evolve",
    "```",
    "",
    "Candidate score is not difficulty evidence. Probe-ready is not trialed. Surface coverage is not",
    "axis diversity. The workbench routes evidence; it does not prove a benchmark is hard.",
    "",
    "## Summary",
    "",
    "| item | value |",
    "|---|---:|",
    `| total candidates | ${summary.totalCandidates} |`,
    `| mechanisms referenced | ${Object.keys(summary.byMechanism).length} |`,
    `| domains represented | ${Object.keys(summary.byDomain).length} |`,
    `| expected next-batch build hours | ${summary.expectedNextBatchHours} |`,
    `| expected next-batch trial cost | ${money(summary.expectedNextBatchTrialCostUsd)} |`,
    `| expected next-batch axes | ${summary.expectedNextBatchAxes} |`,
    `| registry mechanisms available | ${registry.mechanisms.length} |`,
    "",
    "## Recommended Actions",
    "",
    "| action | candidates |",
    "|---|---:|",
    ...DISCOVERY_NEXT_STEPS.map((action) => `| ${action} | ${summary.byRecommendedAction[action] ?? 0} |`),
    "",
    "## Top 10 Build/Probe Candidates",
    "",
    "| candidate | domain | score | confidence | recommended action | cheapest evidence | probe status | blockers |",
    "|---|---|---:|---:|---|---|---|---|",
    ...summary.topBuildOrProbeCandidates.map((s) => {
      const candidate = candidateById(workbench.candidates).get(s.candidateId);
      const status = evidence.get(s.candidateId);
      return `| \`${s.candidateId}\` | ${esc(candidate?.domain ?? "unknown")} | ${s.totalScore.toFixed(1)} | ${s.confidence.toFixed(2)} | ${s.recommendedAction} | ${s.cheapestNextEvidence} | ${evidenceCell(status)} | ${esc(s.blockingReasons.map((b) => b.code).join(", ") || "none")} |`;
    }),
    "",
    "## Probe Evidence Overlay",
    "",
    summary.evidenceStatuses.length === 0
      ? "_No executable mechanism probes have been run for the current discovery pool._"
      : "| candidate | status | probe | verdict | queue reason |",
    ...(summary.evidenceStatuses.length === 0
      ? []
      : [
          "|---|---|---|---|---|",
          ...summary.evidenceStatuses.map(
            (item) =>
              `| \`${item.candidateId}\` | ${item.status} | \`${item.sourceId}\` | ${item.verdict} | ${reason(item.reason)} |`,
          ),
        ]),
    "",
    "## Lineage Feedback Overlay",
    "",
    lineageEvidence.length === 0
      ? "_No lineage-derived portfolio feedback is active._"
      : "| candidate | lineage status | adjustment | reason |",
    ...(lineageEvidence.length === 0
      ? []
      : [
          "|---|---|---:|---|",
          ...lineageEvidence.map(
            (item) =>
              `| \`${item.candidateId}\` | ${item.status} | ${item.rankBoost > 0 ? "+" : ""}${item.rankBoost.toFixed(1)} | ${esc(item.reason)} |`,
          ),
        ]),
    "",
    "## Candidates By Domain",
    "",
    "| domain | candidates |",
    "|---|---:|",
    ...sortedRows(summary.byDomain),
    "",
    "## Candidates By Mechanism",
    "",
    "| mechanism | candidates |",
    "|---|---:|",
    ...sortedRows(summary.byMechanism),
    "",
    "## Cheap Kills",
    "",
    ...killed,
    "",
    "## Needs Repair Or More Paper Evidence",
    "",
    ...repair,
    "",
    "## Transfer Opportunities",
    "",
    ...transfers,
    "",
    "## Surface Coverage",
    "",
    "Surface coverage is separate from defect-axis diversity. A broad product/API surface can still",
    "measure one defect, and a strong defect axis can still cover one narrow product surface.",
    "",
    "| coverage group | distinct tags | tags |",
    "|---|---:|---|",
    ...SURFACE_COVERAGE_GROUPS.map((group: SurfaceCoverageGroup) => {
      const tags = summary.surfaceCoverage.groups[group];
      return `| ${group} | ${tags.length} | ${tags.map((t) => `\`${t}\``).join(", ")} |`;
    }),
    `| defect mechanisms | ${summary.surfaceCoverage.defectMechanisms.length} | ${summary.surfaceCoverage.defectMechanisms.map((t) => `\`${t}\``).join(", ")} |`,
    "",
    "## Warnings",
    "",
    ...warnings.map((w) => `- ${w}`),
    "",
    "## Full Queue",
    "",
    "| candidate | domain | score | confidence | recommended action | cheapest evidence | blockers |",
    "|---|---|---:|---:|---|---|---|",
    ...scoreRows(summary.scores, workbench.candidates),
    "",
    "## Evidence Routing Rules",
    "",
    "- Do not promote raw difficulty if fairness or verifier feasibility is low.",
    "- Do not run model trials when paper/static/local/mutant evidence can decide the next step.",
    "- Do not treat repeated same-provider runs as cross-lab breadth.",
    "- Do not call a transfer path proven until the target domain has required evidence.",
    "- Do not treat surface breadth as independent failure-axis breadth.",
    "- Do not let a score-only candidate outrank a lower-score candidate with better executable probe evidence.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}
