import {
  BROWSER_BACKED_FAMILY_ID,
  BROWSER_BACKED_STATUS,
  BROWSER_HARNESS_REQUIREMENTS,
  type BrowserHarnessPlan,
  browserHarnessPlanFailures,
} from "../families/ui-replay-browser-backed/harness.js";
import { BROWSER_BACKED_SPEC_MD } from "../families/ui-replay-browser-backed/spec.js";

const NEXT_PLAN: BrowserHarnessPlan = {
  driver: "playwright",
  ownsEffectLedger: true,
  exposesPersistentHandlesToSubject: false,
  recordsModelCalls: true,
  finiteSettleBudget: true,
  sealsBeforeGrading: true,
  preservesBrowserTrace: true,
};

export function renderBrowserBackedScaffold(): string {
  const failures = browserHarnessPlanFailures(NEXT_PLAN);
  return [
    "# ui-replay-browser-backed scaffold",
    "",
    `Family: \`${BROWSER_BACKED_FAMILY_ID}\`. Status: **${BROWSER_BACKED_STATUS.stage}**.`,
    "",
    "This is the concrete next step after `ui-replay-live-dom`. It is a scaffold, not a measured",
    "family. Live-DOM remains `dom-like`; no existing trial is browser-backed.",
    "",
    "| item | value |",
    "|---|---|",
    `| intended driver | ${NEXT_PLAN.driver} |`,
    `| spec bytes | ${BROWSER_BACKED_SPEC_MD.length} |`,
    `| harness requirements | ${BROWSER_HARNESS_REQUIREMENTS.length} |`,
    `| plan failures | ${failures.length === 0 ? "none in scaffold plan" : failures.join("; ")} |`,
    "| measured scenarios | 0 |",
    "| counted trials | 0 |",
    "",
    "## Required Properties",
    "",
    ...BROWSER_HARNESS_REQUIREMENTS.map((r) => `- ${r}`),
    "",
    "## Graduation Criteria",
    "",
    "- Implement a Playwright or equivalent driver that owns the browser context.",
    "- Move scenario construction from reducer-only DOM-like trees to real pages with the same",
    "  conflict classes: aria-busy lying, stale handles, selector divergence, mutation during replay,",
    "  finite settling and hidden confirmations.",
    "- Keep the effect ledger outside subject control, seal it before grading and preserve the browser",
    "  trace with transcript, submission and verifier output.",
    "- Rebuild the visible package and hash-gate every trial. Old Live-DOM trials remain evidence for",
    "  the DOM-like descendant only.",
    "",
    "Measured: scaffold completeness only. Mutant-detection: not-run. Real-agent difficulty: not-run.",
    "Browser-backed: not implemented.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}
