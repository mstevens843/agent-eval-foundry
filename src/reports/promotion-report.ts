const esc = (value: string): string => value.replace(/\|/g, "\\|");

export function renderPromotionNext(promotions: readonly ProbeToFamilyPromotion[]): string {
  const ranked = [...promotions].sort(
    (a, b) =>
      statusRank(a.status) - statusRank(b.status) ||
      a.expectedBuildHours - b.expectedBuildHours ||
      a.id.localeCompare(b.id),
  );
  return [
    "promotion next actions",
    "promotion | family | source probe | status | first smoke provider | reason",
    ...ranked.map(
      (p) =>
        `${p.id} | ${p.familyId} | ${p.sourceProbeId} | ${p.status} | ${p.expectedFirstSmokeTrialProvider} | ${p.promotionReason}`,
    ),
    "",
    "Promotion records are local build-routing evidence, not real-agent difficulty evidence.",
    "",
  ].join("\n");
}

export function renderPromotionScaffoldSummary(scaffold: PromotionScaffold): string {
  return [
    `promotion  ${scaffold.promotionId}`,
    `family     ${scaffold.familyId}`,
    `files      ${scaffold.files.length}`,
    ...scaffold.files.map((file) => `- ${file.path}`),
    "",
  ].join("\n");
}

export function renderPromotionReport(
  records: readonly PromotedFamilyRecord[],
  probeSummary: ProbeRunSummary,
  builtFamilies: readonly BuiltFamily[],
  smokeGates: ReadonlyMap<string, PromotionSmokeGateResult> = new Map(),
): string {
  const builtById = new Map(builtFamilies.map((family) => [family.id, family]));
  const selected = records.find((record) => record.promotion.status === "family-built") ?? records[0] ?? null;
  return [
    "# Promoted Family Build Pipeline v1",
    "",
    "This report covers the bridge from discovery candidate to mechanism probe to full validation-mode",
    "family. Promotion evidence is separate from mutant-detection evidence and real-agent difficulty.",
    "",
    "## Summary",
    "",
    "| item | value |",
    "|---|---:|",
    `| promotions recorded | ${records.length} |`,
    `| family-built promotions | ${records.filter((r) => r.promotion.status === "family-built").length} |`,
    `| probe-promoted sources | ${records.filter((r) => r.sourceProbeResult?.verdict === "promote_to_task_shape").length} |`,
    `| counted real-agent trials claimed by promotions | ${records.reduce((sum, r) => sum + r.promotion.evidence.countedAgentTrials, 0)} |`,
    "",
    "## Selected Promotion",
    "",
    ...(selected === null
      ? ["No promotion records are present.", ""]
      : renderSelected(
          selected,
          builtById.get(selected.promotion.familyId),
          smokeGates.get(selected.promotion.familyId),
        )),
    "## Promotion Ledger",
    "",
    "| promotion | family | source candidate | source probe | decision | status | evidence level | probe verdict |",
    "|---|---|---|---|---|---|---|---|",
    ...records.map((record) => {
      const p = record.promotion;
      return `| \`${p.id}\` | \`${p.familyId}\` | \`${p.sourceCandidateId}\` | \`${p.sourceProbeId}\` | ${p.decision} | ${p.status} | ${p.evidence.claimedEvidenceLevel} | ${p.evidence.sourceProbeVerdict} |`;
    }),
    "",
    "## Current Probe Context",
    "",
    `Probe queue size: ${probeSummary.probes.length}. First promoted probe: \`${probeSummary.promoted[0]?.probeId ?? "none"}\`.`,
    "",
    "## Evidence Rules",
    "",
    "- A promotion can justify build work; it cannot claim model difficulty.",
    "- Local reference/mutant/package evidence is validation-mode evidence.",
    "- A full `/6` matrix stays blocked until smoke trial, diagnosis and transfer evidence exist.",
    "- One OpenAI smoke trial, if run later, remains OpenAI-only and not cross-lab breadth.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}

function renderSelected(
  record: PromotedFamilyRecord,
  family: BuiltFamily | undefined,
  smokeGate: PromotionSmokeGateResult | undefined,
): readonly string[] {
  const p = record.promotion;
  const sweep = family?.run();
  const axis = sweep === undefined ? null : measure(sweep.matrix, { nullTrials: 3 });
  return [
    `Selected promoted probe: \`${p.sourceProbeId}\`.`,
    "",
    `Source candidate: \`${p.sourceCandidateId}\`${record.sourceCandidate === null ? "" : ` - ${record.sourceCandidate.title}`}.`,
    "",
    `Why selected: ${p.promotionReason}`,
    "",
    "| evidence | value |",
    "|---|---|",
    `| source probe verdict | ${p.evidence.sourceProbeVerdict} |`,
    `| reference passed probe | ${p.evidence.referencePassed ? "yes" : "no"} |`,
    `| bad probe subjects caught | ${p.evidence.badSubjectsCaught} |`,
    `| distinct probe checks | ${p.evidence.distinctChecks.map((check) => `\`${check}\``).join(", ")} |`,
    `| claimed evidence level | ${p.evidence.claimedEvidenceLevel} |`,
    `| counted real-agent trials | ${p.evidence.countedAgentTrials} |`,
    "",
    "### What Stayed Fixed",
    "",
    ...p.delta.whatStaysFixed.map((item) => `- ${item}`),
    "",
    "### What Changed",
    "",
    ...p.delta.whatChanges.map((item) => `- ${item}`),
    "",
    "### Risks Introduced",
    "",
    `Fairness: ${p.risksIntroduced.fairness.map(esc).join(" ")}`,
    "",
    `Verifier: ${p.risksIntroduced.verifier.map(esc).join(" ")}`,
    "",
    `Adversarial: ${p.risksIntroduced.adversarial.map(esc).join(" ")}`,
    "",
    `Human solvability: ${p.risksIntroduced.humanSolvability.map(esc).join(" ")}`,
    "",
    "### Local Family Evidence",
    "",
    ...(sweep === undefined || axis === null
      ? ["No built family with this id is registered yet.", ""]
      : [
          "| item | value |",
          "|---|---:|",
          `| measured scenarios | ${sweep.scenarioCount} |`,
          `| declared space size | ${sweep.spaceSize} |`,
          `| reference failures | ${sweep.referenceFailures.length} |`,
          `| intended mutants caught | ${sweep.mutantsCaught.filter((m) => m.caught).length}/${sweep.mutantsCaught.length} |`,
          `| baselines blocked | ${sweep.baselinesBlocked.length}/${sweep.baselinesTotal} |`,
          `| mutant-detection axes | ${axis.independentAxes} |`,
          "",
        ]),
    `Pre-registered confirm signal: ${p.preRegisteredConfirmSignal}`,
    "",
    `Pre-registered kill signal: ${p.preRegisteredKillSignal}`,
    "",
    "### Smoke, Diagnosis And Matrix Gate",
    "",
    ...(smokeGate === undefined
      ? [
          "Real-agent smoke trial recommendation: prepare one OpenAI/Codex smoke trial only after package",
          "hash is frozen. A full matrix is blocked.",
          "",
        ]
      : [
          "| item | status |",
          "|---|---|",
          `| local evidence | ${smokeGate.localEvidenceStatus} |`,
          `| smoke campaign | ${smokeGate.smokeCampaignStatus} |`,
          `| smoke diagnosis | ${smokeGate.smokeDiagnosisStatus} |`,
          `| transfer declaration | ${smokeGate.transferDeclarationStatus} |`,
          `| matrix readiness | ${smokeGate.matrixReadinessStatus} |`,
          `| pipeline state | \`${smokeGate.state}\` |`,
          "",
          smokeGate.blockers.length === 0
            ? "No promotion smoke/matrix blockers remain in this gate calculation."
            : ["Blockers:", "", ...smokeGate.blockers.map((blocker) => `- ${blocker}`)].join("\n"),
          "",
          `Next action: ${smokeGate.nextAction}`,
          "",
          smokeGate.fullMatrixReady
            ? "Full matrix spend is allowed to be considered, not automatic."
            : smokeGate.smokeCampaignStatus === "planned" ||
                smokeGate.smokeCampaignStatus === "attempted-uncounted"
              ? "Exact smoke command: `node dist/cli.js trials campaign run --family access-token-scope-expansion --only O1`."
              : "No full matrix command is recommended from this gate state.",
          "",
        ]),
  ];
}

const statusRank = (status: ProbeToFamilyPromotion["status"]): number =>
  ({ "family-built": 0, ready: 1, hold: 2, killed: 3 })[status];
