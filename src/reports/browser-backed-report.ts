import { measure } from "../axis-meter.js";
import {
  type BrowserBackedMeasurement,
  browserBackedMeasurementMatrix,
  validateBrowserBackedMeasurement,
} from "../families/ui-replay-browser-backed/measurement.js";
import {
  BROWSER_BACKED_INTENDED_CHECK,
  BROWSER_BACKED_SCENARIOS,
} from "../families/ui-replay-browser-backed/scenarios.js";

const yesNo = (v: boolean): string => (v ? "yes" : "no");

export function renderBrowserBackedReport(measurement: BrowserBackedMeasurement | null): string {
  const validation = validateBrowserBackedMeasurement(measurement);
  const rows =
    measurement === null
      ? []
      : measurement.cells.map(
          (cell) =>
            `| \`${cell.scenarioId}\` | \`${cell.subjectId}\` | ${cell.failures.length === 0 ? "pass" : cell.failures.map((f) => `\`${f}\``).join(", ")} | \`${cell.artifacts.browserTracePath}\` | \`${cell.artifacts.effectLedgerPath}\` |`,
        );
  return [
    "# ui-replay-browser-backed report",
    "",
    "This report covers the first Playwright-backed descendant slice inside `agent-eval-foundry`.",
    "It is browser-backed mutant-detection evidence only. It is not a counted real-agent trial and",
    "does not upgrade `ui-replay-live-dom` from dom-like to browser-backed.",
    "",
    "| item | value |",
    "|---|---|",
    `| measurement present | ${yesNo(measurement !== null)} |`,
    `| validation | ${validation.valid ? "pass" : "**FAIL**"} |`,
    `| driver | ${measurement?.driver ?? "none"} |`,
    `| engine | ${measurement?.browserEngine ?? "none"} |`,
    `| browser executable | ${measurement?.browserExecutable ?? "none"} |`,
    `| measured scenarios | ${validation.scenariosMeasured} |`,
    `| measured subjects | ${validation.subjectsMeasured} |`,
    `| measured cells | ${measurement?.cells.length ?? 0} |`,
    "| real-agent difficulty | not-run |",
    "",
    "## Scenario Coverage",
    "",
    "| scenario | cases |",
    "|---|---|",
    ...BROWSER_BACKED_SCENARIOS.map(
      (scenario) => `| \`${scenario.scenarioId}\` | ${scenario.cases.join(", ")} |`,
    ),
    "",
    "## Cell Results",
    "",
    rows.length === 0
      ? "No Playwright-backed measurement artifact is preserved."
      : "| scenario | subject | failures | browser trace | effect ledger |",
    ...(rows.length === 0 ? [] : ["|---|---|---|---|---|", ...rows]),
    "",
    "## Validation",
    "",
    validation.failures.length === 0
      ? "All reference cells pass and every known-bad browser strategy trips its intended check."
      : validation.failures.map((failure) => `- ${failure}`).join("\n"),
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}

export function renderBrowserBackedAxisReport(measurement: BrowserBackedMeasurement | null): string {
  const validation = validateBrowserBackedMeasurement(measurement);
  if (measurement === null || !validation.valid) {
    return [
      "# ui-replay-browser-backed axis report",
      "",
      "Browser-backed mutant-detection axes are not claimed until a valid Playwright measurement",
      "artifact exists.",
      "",
      "| item | value |",
      "|---|---|",
      `| measured scenarios | ${validation.scenariosMeasured} |`,
      `| measured subjects | ${validation.subjectsMeasured} |`,
      `| validation failures | ${validation.failures.length === 0 ? "none" : validation.failures.join("; ")} |`,
      "",
      "Real-agent difficulty: not-run.",
      "",
      "---",
      "",
      "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
      "",
    ].join("\n");
  }
  const axis = measure(browserBackedMeasurementMatrix(measurement), { nullTrials: 3 });
  return [
    "# ui-replay-browser-backed axis report",
    "",
    "Measured: Playwright-backed mutant-detection spike. Real-agent difficulty: not-run.",
    "",
    "| item | value |",
    "|---|---:|",
    `| scenarios | ${validation.scenariosMeasured} |`,
    `| known-bad subjects | ${measurement.subjectsMeasured - 1} |`,
    `| independent mutant-detection axes | ${axis.independentAxes} |`,
    `| distinct failure sets | ${axis.distinctMeasurements} |`,
    "",
    "## Intended Checks",
    "",
    "| subject | intended check |",
    "|---|---|",
    ...Object.entries(BROWSER_BACKED_INTENDED_CHECK).map(
      ([subject, check]) => `| \`${subject}\` | \`${check}\` |`,
    ),
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}
