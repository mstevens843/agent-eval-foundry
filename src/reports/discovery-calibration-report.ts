import type { DiscoveryCalibrationSummary } from "../foundry/discovery-calibration.js";

const esc = (s: string): string => s.replace(/\|/g, "\\|");

export function renderDiscoveryCalibrationReport(summary: DiscoveryCalibrationSummary): string {
  return [
    "# Discovery Calibration",
    "",
    "This is a directional backtest of Discovery Workbench scoring against six known family outcomes.",
    "It is n=6 local calibration, not a statistical estimate of benchmark yield.",
    "",
    "The question is whether the scoring model would have routed known families toward the right next",
    "evidence tier: build, evolve, transfer, repair or kill. It does not create new model evidence.",
    "",
    "## Summary",
    "",
    "| item | value |",
    "|---|---:|",
    `| calibration rows | ${summary.n} |`,
    `| matches | ${summary.matches} |`,
    `| partials | ${summary.partials} |`,
    `| misses | ${summary.misses} |`,
    "",
    summary.directionality,
    "",
    "## Backtest Rows",
    "",
    "| family | retrofit candidate | score | recommended action | actual outcome | match | probe evidence |",
    "|---|---|---:|---|---|---|---|",
    ...summary.records.map(
      (record) =>
        `| \`${record.familyId}\` | \`${record.candidateId}\` | ${record.score.totalScore.toFixed(1)} | ${record.score.recommendedAction} | ${esc(record.actualOutcome)} | ${record.recommendationMatched} | ${record.probeEvidence} |`,
    ),
    "",
    "## What The Model Overvalued",
    "",
    ...summary.records.map((record) => `- \`${record.familyId}\`: ${record.overvalued.map(esc).join("; ")}`),
    "",
    "## What The Model Undervalued",
    "",
    ...summary.records.map((record) => `- \`${record.familyId}\`: ${record.undervalued.map(esc).join("; ")}`),
    "",
    "## Scoring Adjustments",
    "",
    ...summary.scoringAdjustments.map((adjustment) => `- ${adjustment}`),
    "",
    "## Row Notes",
    "",
    ...summary.records.flatMap((record) => [
      `### ${record.familyId}`,
      "",
      `Expected route: ${record.expectedRoute}.`,
      "",
      `Evidence label: ${record.evidenceLabel}.`,
      "",
      `Candidate features: ${record.candidateFeatures.map((feature) => `\`${feature}\``).join(", ")}.`,
      "",
      `Calibration note: ${record.scoringAdjustment}`,
      "",
    ]),
    "## Evidence Boundaries",
    "",
    "- Calibration is directional because the local known-outcome set has only six rows.",
    "- A matched recommendation does not prove the next candidate is hard.",
    "- A miss is useful evidence about routing pressure, not a reason to hide the row.",
    "- Probe evidence can update the queue, but still remains below task-family and real-agent evidence.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}
