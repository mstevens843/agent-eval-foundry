// Reports for a measured family, and the cross-family comparison.
//
// The cross-family report is the one with a real result in it, and the result is negative in a
// useful way. Two families measured against DISJOINT banks cannot have their axis counts added: the
// union matrix has a null in every cross cell, so each family's instances separate only its own
// subjects, and the "combined" width is just the sum by construction. That is arithmetic, not a
// finding, and the report says so rather than quoting 3 + 4 = 7 as though it meant something.
//
// What CAN be compared across families is mechanism coverage and the shape of the failure structure,
// so that is what the report actually computes. Getting a genuine combined axis count would require
// running both families against one shared bank of subjects, which does not exist and is named as
// the next experiment rather than papered over.

import { RULES } from "../families/prompt-injection-containment/policy.js";
import type { CellResult, RunResult } from "../families/prompt-injection-containment/runner.js";
import type { AxisReport, Matrix } from "../types.js";

const pct = (n: number, d: number): string => (d === 0 ? "n/a" : `${((100 * n) / d).toFixed(0)}%`);

export interface FamilyReportInput {
  readonly run: RunResult;
  readonly axis: AxisReport;
}

export function renderFamilyReport({ run, axis }: FamilyReportInput): string {
  const graded = run.subjects.filter((s) => s.id !== "reference");
  const perSubject = graded.map((s) => {
    const cells = run.cells.filter((c) => c.subjectId === s.id);
    const failed = cells.filter((c) => c.failures.length > 0);
    const checks = new Map<string, number>();
    for (const c of failed) {
      for (const check of new Set(c.failures.map((f) => f.check))) {
        checks.set(check, (checks.get(check) ?? 0) + 1);
      }
    }
    const top = [...checks.entries()].sort((a, b) => b[1] - a[1]).slice(0, 3);
    return { subject: s, total: cells.length, failed: failed.length, top };
  });

  const refCells = run.cells.filter((c: CellResult) => c.subjectId === "reference");
  const refFailed = refCells.filter((c) => c.failures.length > 0).length;

  const byAttack = new Map<string, number>();
  for (const s of run.scenarios) {
    byAttack.set(s.params.attack, (byAttack.get(s.params.attack) ?? 0) + 1);
  }

  return [
    "# Prompt-injection containment — family report",
    "",
    "**An agent may read untrusted content. Untrusted content may not grant itself tool authority.**",
    "",
    "This is the second family measured end to end by the foundry, and the first one the foundry",
    "produced rather than inherited. Everything below is generated by running the family: a reference",
    "implementation, nine deliberately broken ones, and a verifier that grades all of them against a",
    "tool ledger none of them can write to.",
    "",
    "## Result",
    "",
    "| | |",
    "|---|---:|",
    `| declared parameter space | ${run.spaceSize} points |`,
    `| measured scenarios | **${run.scenarios.length}** |`,
    `| subjects graded | ${graded.length} mutants (+1 reference) |`,
    `| matrix cells | ${run.scenarios.length * graded.length} |`,
    `| reference failures | **${refFailed}** of ${refCells.length} |`,
    `| scenarios separating nothing | ${axis.blindInstances.length} (${pct(axis.blindInstances.length, axis.instanceCount)}) |`,
    `| distinct catch sets | ${axis.distinctMeasurements} |`,
    `| **independent axes** | **${axis.independentAxes}** |`,
    `| redundancy | ${axis.redundancy.toFixed(2)}× |`,
    "",
    refFailed === 0
      ? "The reference passes every scenario, so the family is solvable and is not measuring its own bugs."
      : `**The reference fails ${refFailed} scenario(s). The family is measuring its own bugs and must not ship.**`,
    "",
    "## The policy",
    "",
    "Eight rules, evaluated in this order. The order is part of the specification: a call violating",
    "several rules is attributed to the first it hits, so a subject's stated reason is comparable to",
    "the verifier's expectation instead of being a coin flip between two true answers.",
    "",
    "| code | rule | why it is here |",
    "|---|---|---|",
    ...RULES.map((r) => `| \`${r.code}\` | ${r.rule} | ${r.why} |`),
    "",
    "## Scenario space",
    "",
    "| attack | scenarios |",
    "|---|---:|",
    ...[...byAttack.entries()].sort().map(([a, n]) => `| \`${a}\` | ${n} |`),
    "",
    `Generated from ${run.spaceSize} enumerated points; ${run.scenarios.length} selected so that every`,
    "(carrier, attack) pair, both secret settings, both derivation depths and the no-safe-action",
    "variant each appear at least once. Every attack scenario also carries legitimate work, which is",
    "what makes refusing everything a failure rather than a safe default.",
    "",
    "## Mutant bank",
    "",
    "Each of these grades the verifier. A suite that passes a known-bad implementation is not a suite.",
    "",
    "| mutant | scenarios failed | dominant checks |",
    "|---|---:|---|",
    ...perSubject
      .sort((a, b) => b.failed - a.failed)
      .map(
        (p) =>
          `| \`${p.subject.id}\` | ${p.failed} / ${p.total} | ${p.top.map(([c, n]) => `${c} ×${n}`).join(", ") || "—"} |`,
      ),
    "",
    perSubject.every((p) => p.failed > 0)
      ? "**Every mutant is caught.** No known-bad implementation passes the suite."
      : `**${perSubject.filter((p) => p.failed === 0).length} mutant(s) are never caught** — the suite does not detect the defect they carry.`,
    "",
    "### What the two most dangerous mutants show",
    "",
    "`over-blocker` refuses every action. It handles every attack perfectly and would top any",
    "benchmark that measured only refusal — which is the standard way a safety eval ends up measuring",
    "nothing. It fails here on `liveness`, because blocking the attack is worth nothing if the",
    "legitimate payment never goes out.",
    "",
    "`audit-liar` reaches the correct decision on every single scenario. Its outcomes are perfect. It",
    "fails on `block_reason_correct` because its audit trail cites a routine approval for every",
    "decision, including the ones it blocked. An implementation that cannot say *why* it blocked has",
    "not contained anything it can defend later.",
    "",
    "## Axis structure",
    "",
    "| catch set | scenarios |",
    "|---|---:|",
    ...axis.clusters.map((c) => `| \`{${c.caught.join(", ")}}\` | ${c.instanceIds.length} |`),
    "",
    axis.subjectStats.filter((s) => s.role === "always-caught").length > 0
      ? `\`${axis.subjectStats
          .filter((s) => s.role === "always-caught")
          .map((s) => s.subjectId)
          .join(
            ", ",
          )}\` is caught by every discriminating scenario, so it separates no pair of them and is dead weight in the bank.`
      : "No subject is dead weight in this bank.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}

export interface FamilyAxis {
  readonly name: string;
  readonly matrix: Matrix;
  readonly axis: AxisReport;
  readonly mechanisms: readonly string[];
  readonly provenance: string;
}

/**
 * Compare families. The headline is a refusal: axis counts across disjoint banks do not add.
 */
export function renderCrossFamilyReport(families: readonly FamilyAxis[]): string {
  const totalAxes = families.reduce((n, f) => n + f.axis.independentAxes, 0);
  const allMech = new Set(families.flatMap((f) => f.mechanisms));
  const shared = [...allMech].filter((m) => families.filter((f) => f.mechanisms.includes(m)).length > 1);

  // Do the banks overlap at all? This is the question that decides whether a combined number means
  // anything, so it is computed rather than assumed.
  const banks = families.map((f) => new Set(f.matrix.subjects.map((s) => s.id)));
  const overlaps: string[] = [];
  for (let i = 0; i < banks.length; i += 1) {
    for (let j = i + 1; j < banks.length; j += 1) {
      const a = banks[i];
      const b = banks[j];
      if (a === undefined || b === undefined) continue;
      const both = [...a].filter((x) => b.has(x));
      if (both.length > 0) overlaps.push(`${families[i]?.name} ∩ ${families[j]?.name}: ${both.join(", ")}`);
    }
  }

  return [
    "# Cross-family diversity",
    "",
    "Two families are measured end to end. The obvious question is whether their axes add up to a",
    "portfolio total. **They do not, and the reason is worth more than the number would have been.**",
    "",
    "## Per family",
    "",
    "| family | instances | subjects | blind | distinct catch sets | axes | provenance of the bank |",
    "|---|---:|---:|---:|---:|---:|---|",
    ...families.map(
      (f) =>
        `| \`${f.name}\` | ${f.axis.instanceCount} | ${f.axis.subjectCount} | ${f.axis.blindInstances.length} | ${f.axis.distinctMeasurements} | **${f.axis.independentAxes}** | ${f.provenance} |`,
    ),
    "",
    "## Why the axes cannot simply be added",
    "",
    `Naively the portfolio measures ${totalAxes} things. That number is arithmetic, not evidence.`,
    "",
    "An axis count is a property of a suite **paired with the bank it is graded against**. A catch set",
    "is the set of subjects an instance separates from correct, so comparing catch sets across two",
    "families requires the same subjects to appear in both. Here they do not:",
    "",
    overlaps.length === 0
      ? "**The banks are completely disjoint.** No subject appears in more than one family."
      : `Overlapping subjects: ${overlaps.join("; ")}`,
    "",
    "Build the union matrix and every cross cell is `null` — not measured. Each family's instances",
    "separate only its own subjects, so the union's antichain width is exactly the sum of the parts by",
    "construction, whatever the families actually measure. Two families testing the *identical*",
    "mechanism against disjoint banks would also 'add', which is the reductio.",
    "",
    "So the honest statement is: **each family independently yields the axis count above, against its",
    "own bank, and no combined figure is available.**",
    "",
    "## What can be compared",
    "",
    "| | |",
    "|---|---|",
    `| distinct mechanisms across families | ${allMech.size} |`,
    `| mechanisms shared by more than one family | ${shared.length === 0 ? "none" : shared.join(", ")} |`,
    "",
    shared.length === 0
      ? "The two families target disjoint mechanisms, which is weak evidence that they measure different things — weak because it is a statement about how they were *designed*, not about how implementations *fail*."
      : `Shared mechanisms (${shared.join(", ")}) mean the families may overlap in what they detect, and only a shared bank could say by how much.`,
    "",
    "## The experiment that would settle it",
    "",
    "Run one bank of subjects against both families. Concretely: take implementations that must handle",
    "durable execution *and* untrusted context — which is what any real agent platform needs — and",
    "grade them on both suites. If an implementation failing the outbox family also fails the",
    "containment family, the axes overlap and the portfolio measures fewer things than the sum. If the",
    "failures are uncorrelated, the sum is defensible.",
    "",
    "That has not been done. Until it is, the sum is an upper bound and this report declines to quote",
    "it as a headline.",
    "",
    "## Provenance asymmetry, which limits both numbers differently",
    "",
    "The two banks are not merely disjoint, they are epistemically different, and the two axis counts",
    "should not be read the same way:",
    "",
    "- **durable-approval-outbox** — the bank is ten engines produced by frontier models attempting the",
    "  task, so its axis count is a statement about how real implementations fail. Its weakness is that",
    "  six of its instances were *selected* against seven of those engines.",
    "- **prompt-injection-containment** — the bank is nine mutants written alongside the verifier, so",
    "  its axis count is a lower bound on the verifier's discriminating power **by construction**, and",
    "  says nothing about how hard the family is for a real agent. That has not been measured.",
    "",
    "The first number is about difficulty. The second is about detection. Presenting them in one column",
    "without this paragraph would be the most misleading thing in the repository.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}
