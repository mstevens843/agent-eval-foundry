export function renderDeploymentAliasProviderDeltaDiagnosisReport(diagnosis: ProviderDeltaDiagnosis): string {
  const openAi = diagnosis.subjects.find((subject) => subject.providerFamily === "openai");
  const nonOpenAi = diagnosis.subjects.find(
    (subject) => !["openai", "external", "manual", "unknown"].includes(subject.providerFamily),
  );
  return [
    "# deployment-model-alias-rollout-drift provider-delta diagnosis",
    "",
    "This report explains the mixed smoke result using preserved artifacts only. It does not run a",
    "model, execute a production matrix, or create new difficulty evidence.",
    "",
    "## Verdict",
    "",
    "| item | value |",
    "|---|---|",
    `| family | \`${diagnosis.familyId}\` |`,
    `| challenge hash | \`${diagnosis.challengeHash}\` |`,
    `| scenario set | \`${diagnosis.scenarioSetId}\` |`,
    `| verdicts | ${diagnosis.verdicts.map((verdict) => `\`${verdict}\``).join(", ") || "none"} |`,
    `| route | \`${diagnosis.route}\` |`,
    `| confidence | \`${diagnosis.confidence}\` |`,
    `| confidence reason | ${diagnosis.confidenceReason} |`,
    `| exact next route | ${diagnosis.exactNextRoute} |`,
    "",
    "## Subject Summary",
    "",
    renderSubjectTable(diagnosis.subjects),
    "",
    "## OpenAI Result",
    "",
    subjectResult(openAi, "OpenAI/Codex"),
    "",
    "## Non-OpenAI Result",
    "",
    subjectResult(nonOpenAi, "Claude/Anthropic"),
    "",
    "## Failure Overlap",
    "",
    renderOverlapTable(diagnosis.failureOverlaps),
    "",
    "## OpenAI Failed Checks",
    "",
    openAi === undefined || openAi.failedChecks.length === 0
      ? "No counted OpenAI failed checks."
      : renderCheckTable(openAi.failedChecks),
    "",
    "## Knob Correlations",
    "",
    renderKnobTable(diagnosis.knobDeltas.slice(0, 10)),
    "",
    "## Artifact Strategy Signals",
    "",
    renderMechanismReadings(diagnosis.mechanismReadings),
    "",
    "## What Claude Appears To Handle Correctly",
    "",
    renderArtifactStrengths(nonOpenAi?.artifact ?? null),
    "",
    "## Where OpenAI Failed",
    "",
    renderOpenAiFailureReading(openAi, diagnosis),
    "",
    "## Route",
    "",
    "- Claude solving means this is not cross-lab difficulty evidence.",
    "- OpenAI failing still matters, but only as OpenAI smoke difficulty.",
    "- Mixed provider smoke blocks production `/6` by default.",
    "- The next step is diagnosis/evolution, not matrix spend.",
    "- Same-provider OpenAI repeats can estimate stability only if explicitly approved.",
    "",
    "## Findings",
    "",
    renderFindings("Blockers", diagnosis.blockers),
    "",
    renderFindings("Advisories", diagnosis.advisories),
    "",
    "## Evidence Boundary",
    "",
    "| claim | made? |",
    "|---|---|",
    `| new difficulty evidence | ${diagnosis.evidenceBoundary.claimsNewDifficultyEvidence ? "yes" : "no"} |`,
    `| cross-lab difficulty | ${diagnosis.evidenceBoundary.claimsCrossLabDifficulty ? "yes" : "no"} |`,
    `| matrix readiness | ${diagnosis.evidenceBoundary.claimsMatrixReadiness ? "yes" : "no"} |`,
    `| human evidence | ${diagnosis.evidenceBoundary.claimsHumanEvidence ? "yes" : "no"} |`,
    `| new model trial | ${diagnosis.evidenceBoundary.claimsNewModelTrial ? "yes" : "no"} |`,
    "",
    diagnosis.evidenceBoundary.explanation,
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}

export function renderDeploymentAliasEvolutionOptionsReport(
  plan: DeploymentAliasEvolutionPlan,
  selectedProbeResult: ProbeResult | null = null,
): string {
  return [
    "# deployment-model-alias-rollout-drift evolution options",
    "",
    selectedProbeResult === null
      ? "These are conditional descendants for the mixed provider-delta state. They are not built"
      : "The selected provider-failover route now has executable local probe evidence. These are still not built",
    "families and they are not trial evidence.",
    "",
    "## Decision",
    "",
    "| item | value |",
    "|---|---|",
    `| parent family | \`${plan.parentFamilyId}\` |`,
    `| provider-delta route | \`${plan.currentProviderDeltaRoute}\` |`,
    `| selected proposal | ${plan.selectedProposalId === null ? "none" : `\`${plan.selectedProposalId}\``} |`,
    "",
    plan.reading,
    "",
    "## Selected Executable Probe Evidence",
    "",
    renderSelectedProbeEvidence(plan, selectedProbeResult),
    "",
    "## Proposals",
    "",
    ...plan.proposals.flatMap(renderProposal),
    "## Proposal Findings",
    "",
    plan.findings.length === 0
      ? "No proposal validation findings."
      : [
          "| code | severity | detail |",
          "|---|---|---|",
          ...plan.findings.map(
            (finding) => `| \`${finding.code}\` | ${finding.severity} | ${finding.detail} |`,
          ),
        ].join("\n"),
    "",
    "## Evidence Boundary",
    "",
    selectedProbeResult === null
      ? "- Evolution proposals are routing artifacts, not measured families."
      : "- The selected proposal has executable local probe evidence, not full-family evidence.",
    "- The selected proposal starts as a mechanism probe.",
    selectedProbeResult === null
      ? "- No full descendant should be built until the probe survives cheap validation."
      : "- The selected probe survived cheap validation; a full descendant should still wait for explicit promotion/build scope.",
    "- No model trial was run to produce this report.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}

function renderSelectedProbeEvidence(
  plan: DeploymentAliasEvolutionPlan,
  selectedProbeResult: ProbeResult | null,
): string {
  if (plan.selectedProposalId === null) return "No selected evolution proposal is on record.";
  if (selectedProbeResult === null) {
    return [
      `Selected proposal \`${plan.selectedProposalId}\` has not been matched to an executable probe result yet.`,
      "",
      "Status: proposal-only. Build the mechanism probe before promoting a full descendant family.",
    ].join("\n");
  }
  return [
    "| item | value |",
    "|---|---|",
    `| probe | \`${selectedProbeResult.probeId}\` |`,
    `| verdict | \`${selectedProbeResult.verdict}\` |`,
    `| scenarios | ${selectedProbeResult.scenarioCount} |`,
    `| non-reference subjects caught | ${selectedProbeResult.badSubjectsCaught}/${selectedProbeResult.badSubjectsTotal} |`,
    `| distinct named checks | ${selectedProbeResult.distinctFailedChecks.length} |`,
    `| cheapest next evidence | ${selectedProbeResult.cheapestNextStep} |`,
    "",
    "Status: executable probe evidence. If the draft shape is emitted, it is task-shape-ready; it is still not a built family, package, model trial, or production-matrix gate.",
  ].join("\n");
}

function renderSubjectTable(subjects: readonly ProviderDeltaSubjectComparison[]): string {
  if (subjects.length === 0) return "No subject records are available.";
  return [
    "| run | provider | model | status | graded | failed | artifact | transcript | hash |",
    "|---|---|---|---|---:|---:|---|---|---|",
    ...subjects.map((subject) => {
      const artifact = subject.artifact;
      return `| \`${subject.runId}\` | \`${subject.providerFamily}\` | \`${subject.model ?? "unknown"}\` | \`${subject.status}\` | ${subject.scenariosGraded} | ${subject.scenariosFailed} | ${artifact?.sourcePresent ? "present" : "missing"} | ${artifact?.transcriptPresent ? "present" : "missing"} | ${artifact?.hashCurrent ? "current" : "stale/missing"} |`;
    }),
  ].join("\n");
}

function subjectResult(subject: ProviderDeltaSubjectComparison | undefined, label: string): string {
  if (subject === undefined) return `No ${label} counted smoke record is present.`;
  if (subject.scenariosFailed === 0) {
    return `${label} run \`${subject.runId}\` passed all ${subject.scenariosGraded} graded scenarios.`;
  }
  return `${label} run \`${subject.runId}\` failed ${subject.scenariosFailed} of ${subject.scenariosGraded} graded scenarios.`;
}

function renderOverlapTable(overlaps: readonly ProviderDeltaFailureOverlap[]): string {
  if (overlaps.length === 0) return "No cross-provider pair is available for overlap analysis.";
  return [
    "| pair | left failures | right failures | overlap | jaccard | relation |",
    "|---|---:|---:|---:|---:|---|",
    ...overlaps.map(
      (overlap) =>
        `| \`${overlap.leftRunId}\` / \`${overlap.rightRunId}\` | ${overlap.leftFailures} | ${overlap.rightFailures} | ${overlap.overlap} | ${overlap.jaccard.toFixed(2)} | \`${overlap.relation}\` |`,
    ),
  ].join("\n");
}

function renderCheckTable(checks: readonly { readonly check: string; readonly scenarios: number }[]): string {
  return [
    "| check | scenarios |",
    "|---|---:|",
    ...checks.map((check) => `| \`${check.check}\` | ${check.scenarios} |`),
  ].join("\n");
}

function renderKnobTable(knobs: readonly ProviderDeltaKnobDelta[]): string {
  if (knobs.length === 0) return "No knob correlation is available.";
  return [
    "| knob | discriminates | highest failing value | high rate | low rate |",
    "|---|---|---|---:|---:|",
    ...knobs.map(
      (knob) =>
        `| \`${knob.knob}\` | ${knob.discriminates ? "yes" : "no"} | \`${knob.highestFailingValue}\` | ${(knob.highestFailureRate * 100).toFixed(0)}% | ${(knob.lowestFailureRate * 100).toFixed(0)}% |`,
    ),
  ].join("\n");
}

function renderMechanismReadings(readings: readonly ProviderDeltaMechanismReading[]): string {
  if (readings.length === 0) return "No artifact strategy signals are available.";
  return [
    "| signal | OpenAI | non-OpenAI | reading |",
    "|---|---|---|---|",
    ...readings.map(
      (reading) => `| ${reading.signal} | ${reading.openAi} | ${reading.nonOpenAi} | ${reading.reading} |`,
    ),
  ].join("\n");
}

function renderArtifactStrengths(artifact: ProviderDeltaArtifactInspection | null): string {
  if (artifact === null || !artifact.sourcePresent) {
    return "No preserved non-OpenAI submission source is available for static inspection.";
  }
  const strengths = [
    artifact.signals.authoritativeTruthReferenced
      ? "reads current alias, rollout ledger, eval stream and baseline facades"
      : null,
    artifact.signals.concreteVersionTracked ? "tracks concrete served model versions" : null,
    artifact.signals.baselineComparisonVersioned ? "keeps baseline comparison versioned" : null,
    artifact.signals.canaryWindowHandled ? "models rollout/canary window state" : null,
    artifact.signals.quarantineThresholdHandled ? "handles quarantine thresholds" : null,
    artifact.signals.versionMixHandled ? "handles mixed-version eval streams" : null,
    artifact.signals.idempotencyHandled ? "tracks idempotency/effect ledger state" : null,
    artifact.signals.subjectOwnedTruthRejected ? "explicitly rejects subject-owned truth" : null,
  ].filter((item): item is string => item !== null);
  return strengths.length === 0
    ? "Static inspection found no strong mechanism-specific implementation signals."
    : strengths.map((item) => `- ${item}`).join("\n");
}

function renderOpenAiFailureReading(
  openAi: ProviderDeltaSubjectComparison | undefined,
  diagnosis: ProviderDeltaDiagnosis,
): string {
  if (openAi === undefined) return "No counted OpenAI failure is available.";
  const checks = openAi.failedChecks
    .slice(0, 6)
    .map((check) => `\`${check.check}\``)
    .join(", ");
  const knobs = diagnosis.knobDeltas
    .filter((knob) => knob.discriminates)
    .slice(0, 5)
    .map((knob) => `\`${knob.knob}\``)
    .join(", ");
  return [
    `OpenAI failed ${openAi.scenariosFailed}/${openAi.scenariosGraded} scenarios.`,
    checks.length > 0 ? `Top failed checks: ${checks}.` : "No named checks were preserved.",
    knobs.length > 0
      ? `Failure rates varied most on: ${knobs}.`
      : "No single knob fully explains the failure; this supports diagnosis before spend.",
  ].join("\n\n");
}

function renderFindings(
  title: string,
  findings: readonly { readonly code: string; readonly severity: string; readonly detail: string }[],
): string {
  if (findings.length === 0) return `### ${title}\n\nNone.`;
  return [
    `### ${title}`,
    "",
    "| code | detail |",
    "|---|---|",
    ...findings.map((finding) => `| \`${finding.code}\` | ${finding.detail} |`),
  ].join("\n");
}

function renderProposal(proposal: DeploymentAliasEvolutionProposal): readonly string[] {
  return [
    `### \`${proposal.id}\`${proposal.selected ? " (selected)" : ""}`,
    "",
    "| field | value |",
    "|---|---|",
    `| start as | \`${proposal.startAs}\` |`,
    `| operators | ${proposal.operators.map((operator) => `\`${operator}\``).join(", ")} |`,
    `| truth source | ${proposal.authoritativeTruthSource} |`,
    `| cheapest next evidence | ${proposal.cheapestNextEvidence} |`,
    `| confirm signal | ${proposal.confirmSignal} |`,
    `| kill signal | ${proposal.killSignal} |`,
    "",
    "**What stays fixed:**",
    "",
    ...proposal.whatStaysFixed.map((item) => `- ${item}`),
    "",
    "**What changes:**",
    "",
    ...proposal.whatChanges.map((item) => `- ${item}`),
    "",
    "**Why harder:**",
    "",
    ...proposal.harderBecause.map((item) => `- ${item}`),
    "",
    `**Expected knobs:** ${proposal.expectedKnobs.map((knob) => `\`${knob}\``).join(", ")}`,
    "",
    `**Expected mutants:** ${proposal.expectedMutants.map((mutant) => `\`${mutant}\``).join(", ")}`,
    "",
    "**Risks:**",
    "",
    ...[...proposal.fairnessRisks, ...proposal.verifierRisks, ...proposal.adversarialRisks].map(
      (risk) => `- ${risk}`,
    ),
    "",
  ];
}
