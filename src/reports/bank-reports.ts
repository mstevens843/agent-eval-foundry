// The shared-subject bank and the cross-family axis report.
//
// Two documents, one rule: an axis count belongs to a suite PAIRED WITH THE BANK IT WAS GRADED
// AGAINST, and two counts may only be compared when the banks are made of the same kind of thing.
//
// The temptation these reports exist to refuse is arithmetic. Three built families with measured axis
// counts of 4, 3 and 6 invite a headline of thirteen. Two of those are counts over MUTANTS — a
// statement about what the verifier detects, bounded by how many known-bad implementations somebody
// wrote — and one is a count over real models. Adding them produces a number that answers no
// question, and it is the most quotable number this repository could produce.

import type { BankKind, CrossFamilyClaim, KindedBank } from "../trials/bank.js";
import { BANK_KIND_MEANING } from "../trials/bank.js";
import type { AxisReport } from "../types.js";

export interface BankRow {
  readonly familyId: string;
  readonly kind: BankKind;
  readonly subjects: readonly string[];
  readonly instances: number;
  readonly axes: number | null;
  readonly countedTrials: number;
  readonly note: string;
}

export interface BankReportInput {
  readonly rows: readonly BankRow[];
  readonly claims: readonly CrossFamilyClaim[];
  readonly banks: readonly KindedBank[];
  /** Subjects that appear in more than one bank, whatever the kind. */
  readonly sharedAnywhere: readonly { readonly subject: string; readonly families: readonly string[] }[];
  readonly threshold: number;
}

export function renderSharedBankReport(input: BankReportInput): string {
  const agentRows = input.rows.filter((r) => r.kind === "agent" || r.kind === "imported");
  const mutantRows = input.rows.filter((r) => r.kind === "mutant");

  return [
    "# Shared subject bank",
    "",
    "Which subjects have attempted which families, and what that permits.",
    "",
    "## The two kinds of bank, kept apart",
    "",
    "| kind | what it is | what its axis count means |",
    "|---|---|---|",
    ...(["agent", "imported", "mutant"] as const).map(
      (k) =>
        `| \`${k}\` | ${BANK_KIND_MEANING[k].split(" — ")[0]} | ${BANK_KIND_MEANING[k].split(" — ")[1] ?? ""} |`,
    ),
    "",
    "`assertComparableKinds` refuses to compare across this line in code, not only in prose.",
    "",
    "## Difficulty banks — real subjects",
    "",
    agentRows.length === 0
      ? "_No family has a bank of real subjects._"
      : [
          "| family | subjects | counted trials | instances | axes |",
          "|---|---|---:|---:|---:|",
          ...agentRows.map(
            (r) =>
              `| \`${r.familyId}\` | ${r.subjects.map((s) => `\`${s}\``).join(", ") || "none"} | ${r.countedTrials} | ${r.instances} | ${r.axes ?? "—"} |`,
          ),
        ].join("\n"),
    "",
    "## Detection banks — written mutants",
    "",
    "| family | subjects | instances | axes |",
    "|---|---:|---:|---:|",
    ...mutantRows.map(
      (r) => `| \`${r.familyId}\` | ${r.subjects.length} | ${r.instances} | ${r.axes ?? "—"} |`,
    ),
    "",
    "**These numbers may not be added to the ones above, or to each other as a portfolio total.** A",
    "detection axis says the verifier can tell two hand-written defects apart. That is worth knowing",
    "and it is not a measurement of difficulty.",
    "",
    "## Subjects appearing in more than one family",
    "",
    input.sharedAnywhere.length === 0
      ? "_None. Every subject appears in exactly one family._"
      : [
          "| subject | families |",
          "|---|---|",
          ...input.sharedAnywhere.map(
            (s) => `| \`${s.subject}\` | ${s.families.map((f) => `\`${f}\``).join(", ")} |`,
          ),
        ].join("\n"),
    "",
    "## What each kind of bank currently licenses",
    "",
    ...input.claims.flatMap((claim) => [
      `### \`${claim.kind}\` banks — ${claim.families.length} family(ies)`,
      "",
      `**Verdict:** ${claim.overlap.verdict.toUpperCase()}. ${claim.licensed}.`,
      "",
      claim.overlap.rationale,
      "",
      "**To strengthen this:**",
      "",
      ...claim.toStrengthen.map((t) => `- ${t}`),
      "",
    ]),
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}

export interface CrossFamilyAxisInput extends BankReportInput {
  /** Per family axis report, for the per-suite detail. */
  readonly axisReports: readonly {
    readonly familyId: string;
    readonly kind: BankKind;
    readonly axis: AxisReport;
    /** Null when the bank is too small for a meaningful within-family axis count. */
    readonly axes: number | null;
  }[];
}

export function renderCrossFamilyAxisReport(input: CrossFamilyAxisInput): string {
  const byKind = new Map<BankKind, typeof input.axisReports>();
  for (const r of input.axisReports) byKind.set(r.kind, [...(byKind.get(r.kind) ?? []), r]);

  const mutantTotal = (byKind.get("mutant") ?? []).reduce((n, r) => n + (r.axes ?? 0), 0);
  const agentTotal = [...(byKind.get("agent") ?? []), ...(byKind.get("imported") ?? [])].reduce(
    (n, r) => n + (r.axes ?? 0),
    0,
  );

  return [
    "# Cross-family axes",
    "",
    "What the families measure, together — and the arithmetic this report refuses to do.",
    "",
    "## Per family",
    "",
    "| family | bank | instances | subjects | blind | distinct catch sets | axes |",
    "|---|---|---:|---:|---:|---:|---:|",
    ...input.axisReports.map(
      (r) =>
        `| \`${r.familyId}\` | \`${r.kind}\` | ${r.axis.instanceCount} | ${r.axis.subjectCount} | ${r.axis.blindInstances.length} | ${r.axis.distinctMeasurements} | ${r.axes === null ? "—" : `**${r.axes}**`} |`,
    ),
    "",
    "## The sum that is not available",
    "",
    "| naive total | value | why it is not a result |",
    "|---|---:|---|",
    `| every family added together | ${mutantTotal + agentTotal} | mixes detection and difficulty; the two answer different questions |`,
    `| detection banks added | ${mutantTotal} | the banks are disjoint by construction — no mutant appears in two families, so the union's width is the sum whatever the families measure |`,
    `| difficulty banks added | ${agentTotal} | ${(byKind.get("agent") ?? []).length + (byKind.get("imported") ?? []).length < 2 ? "fewer than two difficulty banks exist" : "excludes one-subject banks; valid only over subjects that attempted both, and the overlap is below threshold"} |`,
    "",
    "A combined axis count requires the same subjects in every bank being combined. Until that holds,",
    "each family's number stands alone and the portfolio total does not exist.",
    "",
    "## What each claim needs",
    "",
    ...input.claims.flatMap((c) => [
      `**\`${c.kind}\`:** ${c.licensed}.`,
      "",
      ...c.toStrengthen.map((t) => `- ${t}`),
      "",
    ]),
    "## The cheapest path to a real cross-family number",
    "",
    "Run the same models against the descendant family until three subjects overlap every difficulty",
    "bank. The local Codex/OpenAI path is executable now; Anthropic/Claude is import-only in this phase",
    "and Gemini remains entitlement-blocked unless that changes:",
    "",
    "```bash",
    "node dist/cli.js trials campaign run --family ui-replay-live-dom --only O2",
    "node dist/cli.js trials campaign prepare --family ui-replay-live-dom --provider external --out bundles/ui-replay-live-dom-external",
    "node dist/cli.js trials campaign import --family ui-replay-live-dom bundles/ui-replay-live-dom-external",
    "```",
    "",
    `That would put additional subjects into the live-DOM descendant bank. ${input.threshold} shared subjects are needed`,
    "before a combined width is worth quoting, because the width is bounded above by the size of the",
    "shared bank and a bound is not a measurement.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic — no timestamp, diffable.",
    "",
  ].join("\n");
}
