import type {
  AdaptiveFunnel,
  AdaptiveFunnelSummary,
  EvidenceCost,
  FunnelNextAction,
  MechanismProbe,
  TransferTest,
} from "../foundry/adaptive-funnel.js";
import { EVIDENCE_COSTS } from "../foundry/adaptive-funnel.js";
import type { Registry } from "../foundry/registry.js";

export interface AdaptiveFunnelReportInput {
  readonly registry: Registry;
  readonly funnel: AdaptiveFunnel;
  readonly summary: AdaptiveFunnelSummary;
}

const esc = (s: string): string => s.replace(/\|/g, "\\|");

const costLabel = (cost: EvidenceCost): string =>
  ({
    paper: "paper",
    static: "static",
    local: "local",
    mutant: "mutant",
    one_agent: "one-agent",
    cross_provider: "cross-provider",
    human: "human",
    adversarial: "adversarial",
  })[cost];

function probeRows(probes: readonly MechanismProbe[]): readonly string[] {
  return probes.map(
    (p) =>
      `| \`${p.id}\` | \`${p.mechanismId}\` | ${p.mode} | ${p.currentStage} | ${p.decision} | ${costLabel(
        p.costEstimate.firstEvidence,
      )} | ${p.transferCandidates.map((t) => `\`${t}\``).join(", ")} |`,
  );
}

function transferRows(transfers: readonly TransferTest[]): readonly string[] {
  return transfers.map(
    (t) =>
      `| \`${t.id}\` | ${t.sourceKind}:\`${t.sourceId}\` | \`${t.transferredMechanism}\` | ${esc(
        t.targetDomain,
      )} | ${t.status} | ${costLabel(t.nextEvidence)} |`,
  );
}

function actionRows(actions: readonly FunnelNextAction[]): readonly string[] {
  return actions.map(
    (a) =>
      `| \`${a.targetId}\` | ${a.targetType} | ${a.mode} | ${a.stage} | ${a.decision} | ${costLabel(
        a.evidenceCost,
      )} | ${esc(a.action)} |`,
  );
}

export function renderFunnelProbes(probes: readonly MechanismProbe[]): string {
  return [
    "# Mechanism probes",
    "",
    "A mechanism probe is smaller than a full benchmark family. It exists to spend the cheapest",
    "useful evidence before authoring a reference, verifier, challenge package and model campaign.",
    "",
    "| probe | mechanism | mode | stage | decision | first evidence | transfer candidates |",
    "|---|---|---|---|---|---|---|",
    ...probeRows(probes),
    "",
    ...probes.flatMap((p) => [
      `## ${p.id}`,
      "",
      `Hypothesis: ${p.hypothesis}`,
      "",
      `Expected failure: ${p.expectedAgentFailure}`,
      "",
      `Truth source: ${p.authoritativeTruthSource.name} - ${p.authoritativeTruthSource.whatItSettles}`,
      "",
      `Hidden behavior declared: ${p.authoritativeTruthSource.hiddenBehaviorDeclared}`,
      "",
      "Cheap screens:",
      "",
      ...p.cheapValidationChecks.map((c) => `- \`${c.id}\` (${costLabel(c.cost)}): ${c.description}`),
      "",
    ]),
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}

export function renderFunnelTransfers(transfers: readonly TransferTest[]): string {
  return [
    "# Transfer tests",
    "",
    "A transfer test carries forward the failure mechanism, not the exact task. It must say what",
    "stays fixed, what changes, and what evidence would make transfer a measured claim.",
    "",
    "| transfer | source | mechanism | target domain | status | next evidence |",
    "|---|---|---|---|---|---|",
    ...transferRows(transfers),
    "",
    ...transfers.flatMap((t) => [
      `## ${t.id}`,
      "",
      `Expected preservation: ${t.expectedFailurePreservation}`,
      "",
      `Fixed: ${t.whatStaysFixed.join("; ")}.`,
      "",
      `Changed: ${t.whatChanges.join("; ")}.`,
      "",
      "Required evidence before transfer is claimed:",
      "",
      ...t.requiredEvidenceBeforeDeclaringTransfer.map((e) => `- ${e}`),
      "",
    ]),
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}

export function renderAdaptiveFunnelReport(input: AdaptiveFunnelReportInput): string {
  const { funnel, registry, summary } = input;
  const byCost = EVIDENCE_COSTS.map(
    (cost) => [cost, summary.nextActions.filter((a) => a.evidenceCost === cost).length] as const,
  ).filter(([, n]) => n > 0);

  return [
    "# Adaptive benchmark-production funnel",
    "",
    "The foundry is no longer a mostly linear task-family funnel. It now has three explicit modes:",
    "`discovery`, `validation` and `production`. The operating rule is simple: spend the cheapest",
    "useful evidence first, and let pass/fail/refusal/ambiguity/stale-hash/axis-collapse outcomes",
    "choose the next action.",
    "",
    "```text",
    "candidate mechanisms",
    "  -> Discovery Mode probes",
    "  -> Validation Mode full family build",
    "  -> one-agent smoke trial",
    "  -> transfer test across a second domain/family",
    "  -> Production Mode matrix",
    "  -> human/adversarial evidence",
    "  -> ship / kill / evolve / hold",
    "```",
    "",
    "## Summary",
    "",
    "| item | value |",
    "|---|---:|",
    `| candidate mechanisms | ${summary.candidateMechanisms} |`,
    `| mechanism probes | ${summary.probes} |`,
    `| probes ready for validation | ${summary.probesReadyForValidation} |`,
    `| probes needing repair/hold | ${summary.probesNeedingRepair} |`,
    `| transfer tests | ${summary.transferTests} |`,
    `| transfer tests ready | ${summary.transferTestsReady} |`,
    `| production-mode families | ${summary.productionModeFamilies.length} |`,
    "",
    "## Cheapest Next Evidence",
    "",
    "| cost tier | queued actions |",
    "|---|---:|",
    ...byCost.map(([cost, n]) => `| ${costLabel(cost)} | ${n} |`),
    "",
    "| target | type | mode | stage | decision | evidence cost | next action |",
    "|---|---|---|---|---|---|---|",
    ...actionRows(summary.nextActions.slice(0, 14)),
    "",
    "## Rules The Planner Enforces",
    "",
    "- Do not run `/6` first.",
    "- Run one counted smoke trial before full matrix spend.",
    "- Run the strongest available opposite provider next only if the smoke failure is on-target.",
    "- Repeated same-provider runs estimate stability, not cross-lab transfer.",
    "- Full matrix is earned, not default.",
    "- Mutant-detection evidence is not real-agent difficulty.",
    "- Provider refusal is not no-bypass evidence.",
    "- Human-ready is not human-evidenced.",
    "- Adversarial-ready is not adversarial-audited.",
    "- Transfer proposed is not transfer proven.",
    "",
    "## Probes",
    "",
    "| probe | mechanism | mode | stage | decision | first evidence | transfer candidates |",
    "|---|---|---|---|---|---|---|",
    ...probeRows(funnel.probes),
    "",
    "## Transfer Tests",
    "",
    "| transfer | source | mechanism | target domain | status | next evidence |",
    "|---|---|---|---|---|---|",
    ...transferRows(funnel.transfers),
    "",
    "## Families Not Ready For Full Matrix",
    "",
    summary.familiesNotReadyForFullMatrix.length === 0
      ? "No family is currently blocked before full matrix by the adaptive planner."
      : [
          "| family | stage | decision | reason |",
          "|---|---|---|---|",
          ...summary.familiesNotReadyForFullMatrix.map(
            (a) => `| \`${a.targetId}\` | ${a.stage} | ${a.decision} | ${esc(a.reason)} |`,
          ),
        ].join("\n"),
    "",
    "## Production-Mode Candidates",
    "",
    summary.productionModeFamilies.length === 0
      ? "No family is automatically recommended for a fresh full matrix by this planner pass."
      : summary.productionModeFamilies.map((f) => `- \`${f}\``).join("\n"),
    "",
    "## Evidence Missing By Family",
    "",
    "| family | next required evidence | reason |",
    "|---|---|---|",
    ...summary.nextActions
      .filter((a) => a.targetType === "family")
      .map(
        (a) => `| \`${a.targetId}\` | ${costLabel(a.evidenceCost)} at \`${a.stage}\` | ${esc(a.reason)} |`,
      ),
    "",
    "## Registry Link",
    "",
    `This report was generated against ${registry.mechanisms.length} mechanisms and ${registry.shapes.length} family shapes. Probe and transfer references are checked against that registry, so a stale mechanism id or family id fails \`node dist/cli.js check\`.`,
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}
