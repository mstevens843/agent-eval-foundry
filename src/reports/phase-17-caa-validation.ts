const cell = (value: string): string => value.replace(/\|/g, "\\|").replace(/\n/g, " ");
const yesNo = (value: boolean): string => (value ? "yes" : "no");
const money = (value: number | null): string => (value === null ? "unpriced" : `$${value.toFixed(4)}`);
const list = (values: readonly string[]): string => (values.length === 0 ? "none" : values.join(", "));

interface ProbeRegistration {
  readonly registrationId: string;
  readonly registrationCorrections: readonly string[];
  readonly correctedContract: {
    readonly verifierCompletions: readonly string[];
    readonly proseOnlyClarifications: readonly string[];
    readonly freshReaderReviewRequired: boolean;
    readonly freshReaderReviewReasoning: string;
  };
  readonly predictions: Readonly<Record<string, unknown>>;
  readonly killRules: readonly { readonly id: string; readonly rule: string }[];
}

interface TrialRegistration {
  readonly registrationCorrections: readonly string[];
  readonly predictions: {
    readonly firstStageCleanSolves: number;
    readonly predictedDecision: string;
    readonly predictedPerTrialFailureProbability: number;
    readonly reasoning: string;
  };
  readonly spendCaps: Readonly<Record<string, number | string>>;
}

