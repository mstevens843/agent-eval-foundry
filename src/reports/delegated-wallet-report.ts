import type { FamilySweep } from "../families/registry.js";
import type { AxisReport } from "../types.js";

export interface DelegatedWalletFamilyReportInput {
  readonly sweep: FamilySweep;
  readonly axis: AxisReport;
  readonly challengeHash: string;
  readonly scenarioSetId: string;
  readonly packageFiles: number;
  readonly packageBytes: number;
  readonly specCodesFound: number;
  readonly space: Readonly<Record<string, readonly unknown[]>>;
  readonly countedAgentTrials: number;
  readonly staleTrials: readonly string[];
}

export function renderDelegatedWalletFamilyReport(input: DelegatedWalletFamilyReportInput): string {
  const caught = input.sweep.mutantsCaught.filter((mutant) => mutant.caught).length;
  return [
    "# delegated-wallet-scope-reconciliation family report",
    "",
    "This is the full descendant family promoted from `delegated-wallet-scope-reconciliation-probe`",
    "after the parent `access-token-scope-expansion` smoke trial passed cleanly. It preserves the",
    "mechanism that requested authority is not approved authority, then adds delegated wallet state,",
    "time separation, revocation, downgrade, prior spend budget, truthful audit and duplicate-effect",
    "pressure.",
    "",
    "## Status",
    "",
    input.countedAgentTrials === 0
      ? "**Local evidence only.** No counted real-agent trial exists for this descendant yet."
      : `**${input.countedAgentTrials} counted real-agent trial(s) exist.** Read the agent-results report before quoting difficulty.`,
    "",
    "| item | value |",
    "|---|---:|",
    `| declared behavior space | ${input.sweep.spaceSize} |`,
    `| measured scenarios | ${input.sweep.scenarioCount} |`,
    `| known-bad subjects and baselines | ${input.sweep.matrix.subjects.length} |`,
    `| reference failures | ${input.sweep.referenceFailures.length} |`,
    `| intended mutants caught | ${caught}/${input.sweep.mutantsCaught.length} |`,
    `| baselines blocked | ${input.sweep.baselinesBlocked.length}/${input.sweep.baselinesTotal} |`,
    `| distinct catch sets | ${input.axis.distinctMeasurements} |`,
    `| mutant-detection axes | ${input.axis.independentAxes} |`,
    `| blind scenarios | ${input.axis.blindInstances.length} |`,
    `| package files | ${input.packageFiles} |`,
    `| package bytes | ${input.packageBytes} |`,
    `| visible rule codes found | ${input.specCodesFound} |`,
    `| scenario set id | \`${input.scenarioSetId}\` |`,
    `| challenge hash | \`${input.challengeHash}\` |`,
    `| counted real-agent trials | ${input.countedAgentTrials} |`,
    `| stale/superseded trials | ${input.staleTrials.length} |`,
    "",
    "## Knobs",
    "",
    "| knob | values |",
    "|---|---:|",
    ...Object.entries(input.space).map(([name, values]) => `| \`${name}\` | ${values.length} |`),
    "",
    "The measured set is sampled deterministically from this declared space and `selectMeasuredSet`",
    "asserts that every declared knob value appears at least once.",
    "",
    "## Mutants",
    "",
    "| mutant/baseline | intended check | caught in scenarios |",
    "|---|---|---:|",
    ...input.sweep.mutantsCaught.map(
      (mutant) => `| \`${mutant.mutantId}\` | \`${mutant.check}\` | ${mutant.caughtIn}/${mutant.total} |`,
    ),
    "",
    "## Evidence Boundary",
    "",
    "- Mutant-detection axes are measured over known-bad subjects; they are not real-agent difficulty.",
    "- The challenge package is leak-checked and hashable, but package readiness is not a trial.",
    "- A single future OpenAI/Codex smoke can produce smoke evidence only, not cross-lab breadth.",
    "- Full `/6` matrix spend remains blocked until smoke diagnosis and transfer evidence justify it.",
    "",
    "---",
    "",
    "Generated by `agent-eval-foundry`. Deterministic - no timestamp, diffable.",
    "",
  ].join("\n");
}
