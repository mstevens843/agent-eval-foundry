// Offline package validation only. Reuse the previously verified execution build.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {cpSync,existsSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const repo=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const out=join(repo,'.local/browser-coverage-v3-2026-09-11');
assert(!existsSync(join(out,'release')),'Use the existing validation evidence; do not overwrite it');mkdirSync(out,{recursive:true});
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const hash=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
const prep=read(join(repo,'reports/screening/evidence/2026-09-11-hardened-next-five-trial-four-preparation.json'));
const source=join(repo,prep.runtime.directory),frozen=join(out,'validation-source');
assert.equal(hash(join(source,'dist/index.js')),prep.runtime.bundleSha256);
if(!existsSync(frozen))cpSync(source,frozen,{recursive:true,verbatimSymlinks:true});
assert.equal(hash(join(frozen,'dist/index.js')),prep.runtime.bundleSha256);
for(const id of ['browser-replay-repair','portfolio-runtime'])cpSync(join(repo,'tasks',id),join(frozen,'tasks',id),{recursive:true});
const api=await import(pathToFileURL(join(source,'dist/index.js')));
const prior=join(repo,'.local/next-five-coverage-v2-2026-09-11/release/browser-replay-repair/export');
const pkg=api.executionPackage(prior),runtime=join(out,'runtime');mkdirSync(runtime,{recursive:true});
writeFileSync(join(runtime,'runtime.json'),Buffer.from(api.readSnapshotFile(pkg.snapshot,'dependencies','runtime.json')));
cpSync(join(prior,'runtime.tar'),join(runtime,'runtime.tar'));
const publicFiles=Object.entries(pkg.snapshot.record.components).flatMap(([component,part])=>part.files.filter(f=>f.path.startsWith('public/')).map(f=>({component,path:f.path,sha256:hash(join(repo,'tasks/browser-replay-repair',f.path))})));
for(const f of publicFiles)assert.equal(f.sha256,createHash('sha256').update(Buffer.from(api.readSnapshotFile(pkg.snapshot,f.component,f.path))).digest('hex'));
writeFileSync(join(out,'public-baseline.json'),JSON.stringify(publicFiles,null,2)+'\n');
execFileSync(process.execPath,[join(frozen,'scripts/verify-selected-portfolio.mjs'),join(out,'release'),runtime,'browser-replay-repair','--release'],{cwd:frozen,stdio:'inherit',timeout:2400000});
for(const f of publicFiles)assert.equal(hash(join(repo,'tasks/browser-replay-repair',f.path)),f.sha256);
console.log(JSON.stringify({validated:true,publicFilesUnchanged:publicFiles.length,providerCallsMade:0}));
