// Regrade an immutable saved submission locally; never dispatch or rewrite its record.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {cpSync,existsSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname,join,relative,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const base=join(root,'.local/browser-coverage-v3-2026-09-11');
const out=join(base,'saved-submission-replay');assert(!existsSync(out));mkdirSync(out);
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const hash=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
const prep=read(join(root,'reports/screening/evidence/2026-09-11-hardened-next-five-trial-four-preparation.json'));
assert.equal(hash(join(root,prep.runtime.directory,'dist/index.js')),prep.runtime.bundleSha256);
const api=await import(pathToFileURL(join(root,prep.runtime.directory,'dist/index.js')));
const id='browser-replay-repair',record=join(root,prep.runRoot,'jobs/real-provider/records',id+'-attempt-1');
const original=api.verifyEvidence(record),completion=hash(join(record,'completion.json'));
const source=join(record,'submission'),exported=join(base,'release',id,'export');
await api.runPortfolioSubmission(exported,source,join(out,'service'));
const cells=read(join(out,'service/result.json')).cells;
assert.equal(cells.length,22);assert(cells.every(c=>c.status==='semantic-pass'));
mkdirSync(join(out,id));
writeFileSync(join(out,id,'authority.json'),JSON.stringify({runtime:read(join(base,'runtime/runtime.json'))}));
cpSync(join(root,'data/hardened-round-four-pass-audit/replay.mjs'),join(out,'run-local.mjs'));
const {check}=await import(pathToFileURL(join(out,'run-local.mjs')));
const bank=read(join(base,'release',id,'oracle-checker/cases/cases.json')).cases;
const truth=read(join(base,'release',id,'oracle-checker/grade-summary.json')).details;
assert.equal(bank.length,14);assert.equal(truth.length,bank.length);
const result=check(id,source,bank,'checker');
const shape=v=>v?.verdicts&&Object.keys(v.verdicts).length===bank.length&&bank.every(c=>Object.hasOwn(v.verdicts,c.token)&&typeof v.verdicts[c.token]?.ok==='boolean');
assert(shape(result.first)&&shape(result.second)&&!result.mutated);
assert(bank.every(c=>result.first.verdicts[c.token].ok===result.second.verdicts[c.token].ok));
const details=bank.map((c,i)=>({token:c.token,candidate:truth[i].candidateId,expected:truth[i].expectedFailingCheck===null,actual:result.first.verdicts[c.token].ok,reasons:result.first.verdicts[c.token].reasons}));
const errors=details.filter(r=>r.expected!==r.actual);
assert(errors.length>0&&errors.every(r=>r.expected===true&&r.actual===false));
api.verifyEvidence(record);assert.equal(hash(join(record,'completion.json')),completion);
const summary={providerCallsMade:0,originalReward:1,diagnosticReward:0,countedReward:null,originalEvidenceModified:false,originalFilesVerified:original.files.length,originalCompletionSha256:completion,packageDigest:read(join(exported,'package.json')).packageDigest,service:{pass:true,correct:22,total:22},checker:{complete:true,deterministic:true,correct:bank.length-errors.length,total:bank.length,pass:false,errors,details},output:relative(root,out)};
writeFileSync(join(out,'summary.json'),JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify(summary));
