import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import {
  auditPhase11Evidence,
  minimumZeroSolveTrials,
  parsePhase10Summary,
  parsePhase11Results,
  renderPhase11DiscoveryReport,
  zeroSolveUpper95,
} from "../src/reports/phase-11-discovery.js";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const readJson = (path: string): unknown => JSON.parse(readFileSync(`${ROOT}/${path}`, "utf8"));
const results = () => parsePhase11Results(readJson("data/phase-11-results.json"));
const phase10 = () => parsePhase10Summary(readJson("data/phase-10-trials.json"));

describe("Phase 11 discovery evidence", () => {
  it("derives the registered zero-solve bounds", () => {
    expect(zeroSolveUpper95(6)).toBeCloseTo(0.393037769, 9);
    expect(zeroSolveUpper95(8)).toBeCloseTo(0.312343978, 9);
    expect(zeroSolveUpper95(9)).toBeLessThan(0.3);
    expect(zeroSolveUpper95(12)).toBeCloseTo(0.220922192, 9);
    expect(minimumZeroSolveTrials(0.3)).toBe(9);
    expect(() => zeroSolveUpper95(0)).toThrow(RangeError);
    expect(() => minimumZeroSolveTrials(1)).toThrow(RangeError);
  });

  it("refuses to count Phase 10 summaries without their durable trial directories", () => {
    const audit = auditPhase11Evidence(ROOT, phase10());

    expect(audit.repoCountableZeroSolveTrials).toBe(6);
    expect(audit.difficultyEvidencedFailures).toBe(0);
    expect(audit.reported).toHaveLength(2);
    expect(audit.reported.every((trial) => !trial.countableArtifactsPresent)).toBe(true);
    expect(audit.reported.every((trial) => trial.missing.includes("challenge"))).toBe(true);
  });

  it("records three searches, one draft, and no independent survivor", () => {
    const discovery = results().discovery;

    expect(discovery.systems).toHaveLength(3);
    expect(discovery.draftedCandidates).toBe(1);
    expect(discovery.survivors).toBe(0);
    expect(discovery.documentsRead).toBe(8);
    expect(discovery.sectionsRead).toBe(18);
    expect(discovery.prediction.result).toBe("falsified");
  });

  it("renders deterministically from the ledger and checked-in artifacts", () => {
    const input = { root: ROOT, results: results(), phase10: phase10() };
    const first = renderPhase11DiscoveryReport(input);
    const second = renderPhase11DiscoveryReport(input);

    expect(first).toBe(second);
    expect(first).toContain("supports **6 clean zero-solve parent trials**, not 8");
    expect(first).toContain("**Verdict: A1.");
    expect(first).toContain("0 survived independent reading.");
    expect(first).toContain("screening instrument today");
    expect(first).toContain("Generated by `agent-eval-foundry`");
  });
});
